#!/usr/bin/env python3
"""Phase 0 tracer bullet for the single-source-of-truth pipeline (not the real generator).

A kernel is a straight-line list of operations. From that one description this script writes
  out/Model.v      the formal model: one Rocq function per kernel over Flocq's rounding operator,
                   parametric in the precision, the minimum exponent and the tie-breaking rule;
  out/kernels.hpp  the C++ code for the same kernels.
Proofs.v (written by hand) proves theorems about Model.v; audit.py checks which axioms they use.

Operations (a, b, c are earlier values):
  add a b      RN(a + b)                      C++: a + b
  sub a b      RN(a - b)                      C++: a - b
  fma a b c    RN(a*b + c)                    C++: std::fma(a, b, c)
  fms a b c    RN(a*b - c)                    C++: std::fma(a, b, -c)
  prod a b     RN(a*b), written as an FMA with a zero addend so that no compiler can contract it
               into a later addition (see ../contraction). Model: RN(a*b + 0), which is what the
               code computes; the proof rewrites the + 0 away.
There is deliberately no plain `mul` whose result could feed an add or sub.
"""
import os, sys

KERNELS = {
    # Knuth's TwoSum: s = RN(a + b), e = (a + b) - s exactly.
    "two_sum": dict(inputs=["a", "b"], outputs=["s", "e"], ops=[
        ("s", "add", "a", "b"), ("bb", "sub", "s", "a"), ("t0", "sub", "s", "bb"),
        ("t1", "sub", "a", "t0"), ("t2", "sub", "b", "bb"), ("e", "add", "t1", "t2")]),
    # Dekker's Fast2Sum: the same when |a| >= |b|.
    "fast_two_sum": dict(inputs=["a", "b"], outputs=["s", "e"], ops=[
        ("s", "add", "a", "b"), ("z", "sub", "s", "a"), ("e", "sub", "b", "z")]),
    # TwoProd with an FMA: p = RN(a*b), e = a*b - p exactly unless the product is too small.
    "two_prod": dict(inputs=["a", "b"], outputs=["p", "e"], ops=[
        ("p", "prod", "a", "b"), ("e", "fms", "a", "b", "p")]),
}

ROCQ = {"add": "rnd ({0} + {1})", "sub": "rnd ({0} - {1})", "fma": "rnd ({0} * {1} + {2})",
        "fms": "rnd ({0} * {1} + - {2})", "prod": "rnd ({0} * {1} + 0)"}
CPP = {"add": "{0} + {1}", "sub": "{0} - {1}", "fma": "std::fma({0}, {1}, {2})",
       "fms": "std::fma({0}, {1}, -{2})", "prod": "std::fma({0}, {1}, T(0))"}

def check(name, k):
    """The IR's own well-formedness: single assignment, uses after definitions, known ops."""
    seen = set(k["inputs"])
    for dst, op, *args in k["ops"]:
        assert op in ROCQ, f"{name}: unknown op {op}"
        assert all(a in seen for a in args), f"{name}: {dst} uses an undefined value"
        assert dst not in seen, f"{name}: {dst} assigned twice"
        seen.add(dst)
    assert all(o in seen for o in k["outputs"])

def rocq():
    out = ["(* Generated by gen.py from the kernel descriptions. Do not edit. *)",
           "From Stdlib Require Import Reals ZArith.", "From Flocq Require Import Core.",
           "Open Scope R_scope.", "", "Section Kernels.",
           "Variable emin prec : Z.", "Variable choice : Z -> bool.",
           "Notation rnd := (round radix2 (FLT_exp emin prec) (Znearest choice)).", ""]
    for name, k in KERNELS.items():
        out.append(f"Definition {name} ({' '.join(k['inputs'])} : R) : {' * '.join('R' for _ in k['outputs'])} :=")
        for dst, op, *args in k["ops"]:
            out.append(f"  let {dst} := {ROCQ[op].format(*args)} in")
        out.append(f"  ({', '.join(k['outputs'])}).\n")
    out.append("End Kernels.")
    return "\n".join(out) + "\n"

def cpp():
    out = ["// Generated by gen.py from the kernel descriptions. Do not edit.", "#pragma once", "#include <cmath>", ""]
    for name, k in KERNELS.items():
        params = ", ".join(f"T {i}" for i in k["inputs"]) + ", " + ", ".join(f"T &{o}_out" for o in k["outputs"])
        out.append(f"template <class T> inline void {name}({params}) {{")
        for dst, op, *args in k["ops"]:
            out.append(f"    const T {dst} = {CPP[op].format(*args)};")
        out += [f"    {o}_out = {o};" for o in k["outputs"]] + ["}", ""]
    return "\n".join(out)

if __name__ == "__main__":
    for name, k in KERNELS.items():
        check(name, k)
    d = sys.argv[1] if len(sys.argv) > 1 else "out"
    os.makedirs(d, exist_ok=True)
    open(os.path.join(d, "Model.v"), "w").write(rocq())
    open(os.path.join(d, "kernels.hpp"), "w").write(cpp())
