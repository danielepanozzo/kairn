#!/usr/bin/env python3
"""Synthetic straight-line networks the size of 8-limb addition and multiplication, to measure
what they cost a client to compile. Not real algorithms: the gates connect pseudo-random wires.

Sizes are extrapolated from the published 2-, 3- and 4-limb accumulation networks (Zhang and
Aiken, SC'25): addition 6, 16, 31 TwoSum gates and multiplication 3, 13, 33 gates after the
partial products; both sequences are quadratic in k (2.5k^2 - 2.5k + 1 and 5k^2 - 15k + 13),
which gives 141 and 213 gates at k = 8. Multiplication adds k(k-1)/2 = 28 TwoProd and 8 plain
products. Writes synth.hpp and client.cpp (CALLS call sites of each)."""
import random, sys
random.seed(8)
K, ADD_GATES, MUL_GATES = 8, 141, 213
calls = int(sys.argv[1]) if len(sys.argv) > 1 else 64

def gates(w, n, prefix):
    """n TwoSum gates on the wire names in w (in place); returns the lines."""
    out = []
    for g in range(n):
        i, j = random.sample(range(len(w)), 2)
        s, e, bb = f"{prefix}s{g}", f"{prefix}e{g}", f"{prefix}b{g}"
        out += [f"    const T {s} = {w[i]} + {w[j]}, {bb} = {s} - {w[i]};",
                f"    const T {e} = ({w[i]} - ({s} - {bb})) + ({w[j]} - {bb});"]
        w[i], w[j] = s, e
    return out

h = ["// Generated by gen_synth.py: networks the SIZE of 8-limb operations (random wiring).",
     "#pragma once", "#include <cmath>",
     "#if SYNTH_INLINE == 2", "#if defined(_MSC_VER) && !defined(__clang__)", "#define SYNTH_FN __forceinline",
     "#else", "#define SYNTH_FN inline __attribute__((always_inline))", "#endif",
     "#elif SYNTH_INLINE == 1", "#define SYNTH_FN inline",
     "#else", "#if defined(_MSC_VER) && !defined(__clang__)", "#define SYNTH_FN __declspec(noinline) inline",
     "#else", "#define SYNTH_FN inline __attribute__((noinline))", "#endif", "#endif",
     "template <class T> struct X8 { T limb[8]; };", ""]
w = [f"a.limb[{i}]" for i in range(K)] + [f"b.limb[{i}]" for i in range(K)]
h += ["template <class T> SYNTH_FN X8<T> add8(const X8<T> &a, const X8<T> &b) {"] + gates(w, ADD_GATES, "")
h += ["    return {{" + ", ".join(w[:K]) + "}};", "}", ""]
w, pre = [], []
for i in range(K):
    for j in range(K - i):
        if i + j < K - 1:  # TwoProd: product (as an FMA with a zero addend) and its error
            pre += [f"    const T p{i}_{j} = std::fma(a.limb[{i}], b.limb[{j}], T(0)), q{i}_{j} = std::fma(a.limb[{i}], b.limb[{j}], -p{i}_{j});"]
            w += [f"p{i}_{j}", f"q{i}_{j}"]
        else:
            pre += [f"    const T p{i}_{j} = std::fma(a.limb[{i}], b.limb[{j}], T(0));"]
            w += [f"p{i}_{j}"]
h += ["template <class T> SYNTH_FN X8<T> mul8(const X8<T> &a, const X8<T> &b) {"] + pre + gates(w, MUL_GATES, "")
h += ["    return {{" + ", ".join(w[:K]) + "}};", "}"]
open("synth.hpp", "w").write("\n".join(h) + "\n")

c = ['#include "synth.hpp"', "// A client function with distinct call sites: a dot product written out term by term.",
     "X8<double> client(const X8<double> *x, const X8<double> *y) {", "    X8<double> s = {};"]
c += [f"    s = add8(s, mul8(x[{i}], y[{i}]));" for i in range(calls)]
c += ["    return s;", "}"]
open("client.cpp", "w").write("\n".join(c) + "\n")
ops = lambda n: 6 * n
print(f"add8: {ADD_GATES} TwoSum gates = {ops(ADD_GATES)} flops; mul8: 28 TwoProd + 8 products + {MUL_GATES} gates = {64 + ops(MUL_GATES)} flops; {calls} call sites of each")
