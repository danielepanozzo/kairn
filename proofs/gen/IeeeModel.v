  let p := prod a b in
  let q0 := prod ah bh in
  let t1 := sub q0 p in
  let q1 := prod ah bl in
  let t2 := add t1 q1 in
  let q2 := prod al bh in
  let t3 := add t2 q2 in
  let q3 := prod al bl in
  let e := add t3 q3 in
  (p, e).

(* two_sum: TwoSum (Knuth, TAOCP vol. 2, 4.2.2; Moller 1965). *)
Definition two_sum (a b : float) : float * float :=
