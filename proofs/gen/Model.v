(* two_prod_dekker: Dekker's product with Veltkamp's split (Dekker 1971); overflow preconditions BM11. *)
Definition two_prod_dekker (a b : R) : R * R :=
  let '(ah, al) := split a in
  let '(bh, bl) := split b in
  let p := rnd (a * b + 0) in
  let q0 := rnd (ah * bh + 0) in
  let t1 := rnd (q0 - p) in
  let q1 := rnd (ah * bl + 0) in
  let t2 := rnd (t1 + q1) in
  let q2 := rnd (al * bh + 0) in
  let t3 := rnd (t2 + q2) in
  let q3 := rnd (al * bl + 0) in
  let e := rnd (t3 + q3) in
  (p, e).

(* two_sum: TwoSum (Knuth, TAOCP vol. 2, 4.2.2; Moller 1965). *)
Definition two_sum (a b : R) : R * R :=
  let s := rnd (a + b) in
  let bb := rnd (s - a) in
  let t0 := rnd (s - bb) in
  let t1 := rnd (a - t0) in
  let t2 := rnd (b - bb) in
  let e := rnd (t1 + t2) in
  (s, e).

