"""Expressions of the claims: `value`, the arguments of a `predicate`, the `set` of an
`encloses` entry.

Grammar (architecture.md, "Claims of the second wave"): names, binary `+`, `-`, `*`, unary
minus, `abs( )` and parentheses.  An expression is compiled, once per format, into Python
source over integers: every leaf is an integer N standing for N * 2^s with a scale s known
before any operand is seen (the format's qmin for a limb sum), a product adds scales and a
sum aligns its operands to the smaller scale with a constant shift.  The exact value of the
expression is then the returned integer times 2^scale, so no verdict needs Fraction.
"""

import re


class ExprError(ValueError):
    pass


_TOKEN = re.compile(r"\s*(?:([A-Za-z_][A-Za-z0-9_]*)|([-+*()]))")
FUNCTIONS = ("abs",)


def parse(text):
    """The syntax tree: ("name", n), ("neg", a), ("abs", a), ("+", a, b), ("-", a, b) or
    ("*", a, b)."""
    if not isinstance(text, str):
        raise ExprError("expression %r is not a string" % (text,))
    toks = []
    s = text.rstrip()
    pos = 0
    while pos < len(s):
        m = _TOKEN.match(s, pos)
        if m is None or m.end() == pos:
            raise ExprError("cannot read expression %r at %r" % (text, s[pos:]))
        pos = m.end()
        toks.append(("name", m.group(1)) if m.group(1) else ("op", m.group(2)))
    toks.append(("end", None))
    i = [0]

    def peek():
        return toks[i[0]]

    def take():
        t = toks[i[0]]
        i[0] += 1
        return t

    def sum_():
        a = prod_()
        while peek() in (("op", "+"), ("op", "-")):
            op = take()[1]
            a = (op, a, prod_())
        return a

    def prod_():
        a = unary_()
        while peek() == ("op", "*"):
            take()
            a = ("*", a, unary_())
        return a

    def unary_():
        if peek() == ("op", "-"):
            take()
            return ("neg", unary_())
        return atom_()

    def atom_():
        t = take()
        if t[0] == "name":
            if t[1] in FUNCTIONS:
                if take() != ("op", "("):
                    raise ExprError("%s must be followed by '(' in %r" % (t[1], text))
                a = sum_()
                if take() != ("op", ")"):
                    raise ExprError("unbalanced parentheses in %r" % text)
                return (t[1], a)
            return ("name", t[1])
        if t == ("op", "("):
            a = sum_()
            if take() != ("op", ")"):
                raise ExprError("unbalanced parentheses in %r" % text)
            return a
        raise ExprError("unexpected %r in %r" % (t[1] if t[1] is not None else "end", text))

    if peek()[0] == "end":
        raise ExprError("empty expression")
    tree = sum_()
    if peek()[0] != "end":
        raise ExprError("trailing input in %r" % text)
    return tree


def names(tree, out=None):
    """The names of a tree in order of appearance, with repetitions."""
    out = [] if out is None else out
    if tree[0] == "name":
        out.append(tree[1])
    else:
        for sub in tree[1:]:
            names(sub, out)
    return out


def uses(tree, kind):
    if tree[0] == kind:
        return True
    return tree[0] != "name" and any(uses(t, kind) for t in tree[1:])


def to_text(tree):
    k = tree[0]
    if k == "name":
        return tree[1]
    if k == "neg":
        return "-(%s)" % to_text(tree[1])
    if k == "abs":
        return "abs(%s)" % to_text(tree[1])
    return "(%s %s %s)" % (to_text(tree[1]), k, to_text(tree[2]))


def compile_tree(tree, leaf):
    """(source, scale): Python source of an integer whose value times 2^scale is the exact
    value of the tree.  leaf(name) gives the (source, scale) of a name."""
    k = tree[0]
    if k == "name":
        return leaf(tree[1])
    if k == "neg":
        c, s = compile_tree(tree[1], leaf)
        return "(-%s)" % c, s
    if k == "abs":
        c, s = compile_tree(tree[1], leaf)
        return "abs(%s)" % c, s
    a, sa = compile_tree(tree[1], leaf)
    b, sb = compile_tree(tree[2], leaf)
    if k == "*":
        return "(%s*%s)" % (a, b), sa + sb
    s = min(sa, sb)
    if sa > s:
        a = "(%s<<%d)" % (a, sa - s)
    if sb > s:
        b = "(%s<<%d)" % (b, sb - s)
    return "(%s%s%s)" % (a, k, b), s


def make_function(params, source):
    """A Python function of `params` computing `source` (generated by compile_tree from a
    parsed tree, so it holds only integer constants, subscripts and arithmetic)."""
    return eval("lambda %s: %s" % (", ".join(params), source), {"__builtins__": {}, "abs": abs})
