"""What the hand-written public headers read from the generator: include/kairn/gen/bounds.hpp and
include/kairn/gen/selftest.hpp.

bounds.hpp says, per kernel and limb type, whether the kernel is proved and, only if it is, the
constants of its error claim, as docs/developer/design/phase0/operations.md defines them ("Exported
constants"): unit >= c u^k, tiny >= t eta, unit_computed >= unit / (1 - unit) and
tiny_computed >= tiny / (1 - unit), where unit and tiny inside the quotients are the exact values,
each printed as the smallest number of the limb type not below the exact rational, and the form
(relative to the exact result, R; to the operands, A; to the terms of the exact value, T: |s| +
|x y| for s + x y, the steps of the dot products). A form other than R has no computed variants:
a bound relative to the operands or to the terms gives none relative to the computed value. An
unverified kernel gets no constants at all: the library cannot export a bound that is only a
target, because there is none to read.
What is proved changes as proofs land, so the library takes it from here, never from its own text.

selftest.hpp holds, per kernel and limb type, fixed operands and the outputs that the exact
interpreter computes for them: the stored bit patterns of kairn::self_test()
(docs/developer/design/phase0/environment.md, "The self-test").
"""
import hashlib
from fractions import Fraction

from . import consts, cpp, expr, interp, ir

HEADER = ('// Generated by gen/kairn-gen from gen/kernels/*.kernel. Do not edit: change the\n'
          '// descriptions or gen/kairn_gen/library.py, then run python3 gen/kairn-gen build.')

# The error forms of the claims (rules.ERROR_FORMS) and their names in bounds.hpp.
FORMS = {'R': 'result', 'A': 'operands', 'T': 'terms'}


class LibraryError(Exception):
    pass


def _literal(v, ctype):
    """A nonnegative dyadic rational as a literal of the limb type."""
    suffix = cpp.TYPES[ctype][1]
    return f'0.0{suffix}' if v == 0 else cpp.hex_literal(Fraction(v), suffix)


def _up(x, ctype):
    v = consts.round_up(x, *cpp.FORMATS[ctype])
    if v is None:
        raise LibraryError(f'{x} rounded up overflows {ctype}')
    return v


def error_entry(k):
    """The error entry whose constants bounds.hpp exports: the only one without a condition, or
    None when the kernel has none. Entries with a condition (`when`) are not exported."""
    plain = [e for e in k.ensures if e['kind'] == 'error' and e['when'] is None]
    if len(plain) > 1:
        raise LibraryError(f'kernel {k.name} has {len(plain)} error claims without a condition; '
                           'bounds.hpp exports one per kernel, so say which in gen/kairn_gen/library.py')
    return plain[0] if plain else None


def constants(k, ctype):
    """{'form', 'unit', 'tiny', 'unit_computed', 'tiny_computed'} of K's error entry in the limb
    type, as Fractions (the last two only for form R), or None when K has no such entry."""
    e = error_entry(k)
    if e is None:
        return None
    p, qmin, _ = cpp.FORMATS[ctype]
    u = Fraction(1, 2 ** p)
    unit = expr.evaluate(expr.parse(e['c']), {'u': u}) * u ** e['k']
    tiny = expr.evaluate(expr.parse(e['t']), {}) * Fraction(2) ** qmin
    if not 0 <= unit < 1 or tiny < 0:
        raise LibraryError(f'kernel {k.name} in {ctype}: needs 0 <= unit < 1 and tiny >= 0')
    out = {'form': e['form'], 'unit': _up(unit, ctype), 'tiny': _up(tiny, ctype)}
    if e['form'] == 'R':
        # A bound relative to the operands, or to the terms, gives none relative to the computed value.
        out['unit_computed'] = _up(unit / (1 - unit), ctype)
        out['tiny_computed'] = _up(tiny / (1 - unit), ctype)
    return out


def proved_for(k, ctype):
    """Whether K is proved for this limb type: status proved, and the type's precision at least
    the kernel's minimum (below it the claims are not stated)."""
    return k.status == 'proved' and (k.min_precision is None or k.min_precision <= cpp.TYPES[ctype][0])


def _claim_text(k):
    kinds = []
    for e in k.ensures:
        if e['kind'] == 'error':
            text = f'error, form {e["form"]}, c = {e["c"]}, k = {e["k"]}, t = {e["t"]}'
            kinds.append(text + (f' when {e["when"]}' if e['when'] else ''))
        else:
            kinds.append(e['kind'])
    return '; '.join(kinds)


def bounds(kernels):
    lines = [HEADER, '//',
             '// What each kernel is proved to guarantee, for the hand-written public headers',
             '// (include/kairn/traits.hpp, and the operations that need no kairn::unverified marker).',
             '// Per kernel K and limb type T, kairn::gen::bounds::K<T> has',
             '//   proved         true exactly when gen/claims.json gives K the status proved and T has',
             '//                  at least K\'s minimum precision;',
             '// and, only when K is proved and has an error claim without a condition,',
             '//   form           result: |computed - exact| <= unit |exact| + tiny,',
             '//                  operands: |computed - exact| <= unit (|x| + |y|) + tiny,',
             '//                  terms: |computed - exact| <= unit (the sum of the magnitudes of the terms',
             '//                  of the exact value: |s| + |x y| for s + x y) + tiny;',
             '//   unit, tiny     the smallest numbers of T not below c u^k and t eta;',
             '//   unit_computed, tiny_computed (form result only)',
             '//                  the smallest numbers of T not below unit / (1 - unit) and tiny / (1 - unit),',
             '//                  with unit and tiny exact: |computed - exact| <= unit_computed |computed| +',
             '//                  tiny_computed (docs/developer/design/phase0/operations.md, "Exported',
             '//                  constants").',
             '// An unverified kernel has no constants here at all: a target is not a bound.',
             '#pragma once', '',
             'namespace kairn::gen::bounds {', '',
             '// What an error bound is relative to.',
             'enum class Form { result, operands, terms };']
    for k in kernels.values():
        status = 'proved' if k.status == 'proved' else 'UNVERIFIED'
        lines += ['', f'// {k.name}: {status}. Claims: {_claim_text(k)}.',
                  f'template <class T> struct {k.name};']
        for ctype in cpp.TYPES:
            if not proved_for(k, ctype):
                why = ''
                if k.status == 'proved':
                    why = (f'  // proved from precision {k.min_precision} on; '
                           f'{ctype} has {cpp.TYPES[ctype][0]}')
                lines.append(f'template <> struct {k.name}<{ctype}> {{ static constexpr bool proved = false; }};'
                             + why)
                continue
            c = constants(k, ctype)
            lines += [f'template <> struct {k.name}<{ctype}> {{', '    static constexpr bool proved = true;']
            if c is not None:
                lines.append(f'    static constexpr Form form = Form::{FORMS[c["form"]]};')
                for name in ('unit', 'tiny', 'unit_computed', 'tiny_computed'):
                    if name in c:
                        lines.append(f'    static constexpr {ctype} {name} = {_literal(c[name], ctype)};')
            lines.append('};')
    lines += ['', '}  // namespace kairn::gen::bounds']
    return '\n'.join(lines) + '\n'


