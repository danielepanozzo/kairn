# The self-test's stored results.

FORMAT_OF = {'double': 'binary64', 'float': 'binary32'}


class _Stream:
    """Deterministic pseudo-random integers from a name: the same operands on every machine and
    with every Python, so that the header does not change unless a kernel does."""

    def __init__(self, name):
        self.name, self.n = name, 0

    def bits(self, n):
        self.n += 1
        h = hashlib.blake2b(f'{self.name}:{self.n}'.encode(), digest_size=16).digest()
        return int.from_bytes(h, 'little') & ((1 << n) - 1)

    def pick(self, lo, hi):
        return lo + self.bits(16) % (hi - lo + 1)


def _number(f, rng, lo, hi, positive=False):
    """A number with a full significand and exponent in [lo, hi]: (-1)^s m 2^(e - p + 1)."""
    m = rng.bits(f.p - 1) | (1 << (f.p - 1))
    return interp.canon(False if positive else bool(rng.bits(1)), m, rng.pick(lo, hi) - f.p + 1)


def _tail(f, rng, x0):
    """A second limb for x0 that keeps (x0, x1) normalized, a few binades below half an ulp."""
    e0 = x0[3] + x0[2].bit_length() - 1                 # x0 in [2^e0, 2^(e0 + 1))
    x1 = _number(f, rng, e0 - f.p - rng.pick(1, 6), e0 - f.p - 1)
    while interp.add(f, x0, x1) != x0:
        x1 = (x1[0], x1[1], x1[2], x1[3] - 1)
    return x1


def _exact(limbs):
    """The exact value of finite limbs, as a Fraction."""
    return sum((-1 if v[1] else 1) * Fraction(v[2]) * Fraction(2) ** v[3] for v in limbs)


def selftest_case(k, kernels, f):
    """Fixed operands of K in format f that satisfy its requirements, and its outputs."""
    rng = _Stream(f'{k.name}:{f.name}')
    req = {}
    for r in k.requires:
        req.setdefault(r[0], []).append(r[1:])
    # Radii are nonnegative: of a ball operand, and the one a ball is made from (otherwise the
    # result would be the empty set, which is not finite).
    nonneg = {r[0] for r in req.get('nonneg', [])} | {r[1] for r in req.get('ball', [])} | \
        {e['from']['radius'] for e in k.ensures if e['kind'] == 'makes_ball' and 'radius' in e['from']}
    # The bounds of an interval, and the bounds an interval or a ball is made from, are put in
    # order, lower first (otherwise the result would be the empty set, which is not finite).
    ordered = [tuple(r) for r in req.get('interval', [])] + \
        [(e['from']['lower'], e['from']['upper']) for e in k.ensures
         if e['kind'] in ('makes_ball', 'makes_interval') and 'lower' in e['from']]
    pow2 = {r[0] for r in req.get('power_of_two', [])}
    counts = {r[0] for r in req.get('count', [])}
    smaller = {r[1] for r in req.get('abs_ge', [])}
    # The mask that gates the result of the finish of a fold of maxima (finite_or_nan if=) is true:
    # otherwise the result is the canonical NaN, which is the non-finite case.
    gates = {e['if'] for e in k.ensures if e['kind'] == 'finite_or_nan' and 'if' in e}
    inputs = []
    for g in k.inputs:
        if g.kind == ir.MASK:
            inputs.append(True if g.name in gates else bool(rng.bits(1)))
        elif g.name in counts:              # a number of terms: an integer from 1 to 1000
            inputs.append(interp.canon(False, rng.pick(1, 1000), 0))
        elif g.name in pow2:
            inputs.append(interp.canon(False, 1, rng.pick(-6, 6)))
        elif g.name in nonneg:
            inputs.append(_number(f, rng, -24, -16, positive=True))
        elif len(g.limbs) == 1:
            # The smaller operand of an abs_ge requirement sits well below the larger one.
            inputs.append(_number(f, rng, -12, -8) if g.name in smaller else _number(f, rng, -3, 3))
        else:
            x0 = _number(f, rng, -3, 3)
            inputs += [x0] + [_tail(f, rng, x0)] * (len(g.limbs) - 1)
            if len(g.limbs) > 2:
                raise LibraryError(f'{k.name}: no operands chosen for groups of more than two limbs')
    at, i = {}, 0
    for g in k.inputs:
        at[g.name] = slice(i, i + len(g.limbs))
        i += len(g.limbs)
    for lo, hi in ordered:
        a, b = inputs[at[lo]], inputs[at[hi]]
        if _exact(a) > _exact(b):
            inputs[at[lo]], inputs[at[hi]] = b, a
    # The two intervals of an intersection overlap (otherwise the result would be the empty set):
    # of their four bounds in order, the first and the third bound one, the second and the fourth
    # the other.
    for e in k.ensures:
        if e['kind'] == 'interval_set' and e['set'] == 'intersection':
            (x, bx), (y, by) = e['intervals'].items()
            names = [bx['lower'], by['lower'], bx['upper'], by['upper']]
            values = sorted((inputs[at[n]] for n in names), key=_exact)
            for n, v in zip(names, values):
                inputs[at[n]] = v
    machine = interp.Machine(kernels)
    out = machine.run(k.name, f, inputs)
    if interp.Machine(kernels, fused=False).run(k.name, f, inputs) != out:
        return inputs, None          # a muladd: either result is correct, so there is no one to store
    for v in out:
        if not isinstance(v, bool) and v[0] != interp.NUM:
            raise LibraryError(f'{k.name} in {f.name}: the fixed operands give a non-finite result')
    return inputs, out


def nonfinite_case(k, kernels, f):
    """For a full kernel or a constructor (a kernel without a real-model statement): the operands
    of selftest_case with the first operand made non-finite, +infinity in binary64 and NaN in
    binary32 (-infinity for an operand required not to be a NaN), in its canonical form ((inf, 0) or (NaN, NaN) for two limbs; for a ball, the whole
    line or the empty set; for an interval, the whole line or the empty set, and for a set
    operation of intervals every operand so), and the outputs. None for any other kernel."""
    if k.real_model:
        return None
    inputs, _ = selftest_case(k, kernels, f)
    inf = f.name == 'binary64'
    special = (interp.INF, False) if inf else interp.NaN
    zero = interp.canon(False, 0, 0)
    balls = {r[1]: r[2] for r in k.requires if r[0] == 'ball'}
    at = {}
    i = 0
    for g in k.inputs:
        at[g.name] = list(range(i, i + len(g.limbs)))
        i += len(g.limbs)
    first = k.inputs[0]
    if first.kind != ir.LIMB:
        raise LibraryError(f'{k.name}: no non-finite case for a kernel whose first input is a mask')
    limbs = at[first.name]
    intervals = {r[1]: r[2] for r in k.requires if r[0] == 'interval'}
    if first.name in balls:                 # the whole line, or the empty set
        for j in limbs:
            inputs[j] = zero if inf else interp.NaN
        inputs[at[balls[first.name]][0]] = special
    elif first.name in intervals:           # the whole line (-inf, +inf), or the empty set (+inf, -inf)
        # Of a set operation (the hull, the intersection), every operand: the hull with the empty set
        # and the intersection with the whole line are the other operand, which is finite.
        sets = any(e['kind'] == 'interval_set' for e in k.ensures)
        for lower in (list(intervals) if sets else [first.name]):
            limbs, upper = at[lower], at[intervals[lower]]
            for j in limbs[1:] + upper[1:]:
                inputs[j] = zero
            inputs[limbs[0]] = (interp.INF, inf)
            inputs[upper[0]] = (interp.INF, not inf)
    elif ('not_nan', first.name) in k.requires:    # +infinity, or -infinity in place of a NaN
        inputs[limbs[0]] = (interp.INF, not inf)
        for j in limbs[1:]:
            inputs[j] = zero
    else:
        inputs[limbs[0]] = special
        for j in limbs[1:]:
            inputs[j] = zero if inf else interp.NaN
    machine = interp.Machine(kernels)
    out = machine.run(k.name, f, inputs)
    if interp.Machine(kernels, fused=False).run(k.name, f, inputs) != out:
        raise LibraryError(f'{k.name}: a non-finite case whose result depends on contraction')
    return inputs, out


def _value(v, ctype):
    if isinstance(v, bool):
        return 'true' if v else 'false'
    if v[0] == interp.INF:
        return f'{"-" if v[1] else ""}std::numeric_limits<{ctype}>::infinity()'
    if v[0] == interp.NAN:
        return f'std::numeric_limits<{ctype}>::quiet_NaN()'
    text = interp.format_limb(v)
    return (text + cpp.TYPES[ctype][1]) if text != '0x0p+0' else '0.0' + cpp.TYPES[ctype][1]


def selftest(kernels):
    lines = [HEADER, '//',
             '// The stored results of kairn::self_test() (docs/developer/design/phase0/environment.md,',
             '// "The self-test"): every kernel, for each limb type, on fixed operands that satisfy its',
             '// requirements, against the outputs the generator\'s exact interpreter computes for them.',
             '// The operands are read through volatile objects, so that the compiler cannot evaluate a',
             '// kernel while it compiles: what runs is the code the client\'s flags produced. The full',
             '// kernels and the constructors of the non-finite layer have a second case each, with a',
             '// non-finite first operand: +infinity for double, NaN for float; an interval operand is',
             '// then the whole line for double and the empty set for float.',
             '#pragma once', '',
             '#include <bit>',
             '#include <cstdint>',
             '#include <limits>', '',
             '#include "scalar.hpp"', '',
             'KAIRN_GEN_PUSH_WARNINGS',
             'namespace kairn::gen::selftest {', '',
             '// Whether a computed limb is the stored one, from the bit patterns: a comparison would read',
             '// a subnormal operand as zero under flush-to-zero, the very thing to detect. Any two NaNs are',
             '// the same, and so are the two zeros: Kairn leaves the sign of a zero unspecified.']
    for ctype, utype, mag, inf in (('double', 'std::uint64_t', '0x7fffffffffffffffu', '0x7ff0000000000000u'),
                                   ('float', 'std::uint32_t', '0x7fffffffu', '0x7f800000u')):
        lines += [f'inline bool same({ctype} a, {ctype} b) noexcept {{',
                  f'    const {utype} x = std::bit_cast<{utype}>(a) & {mag}, y = std::bit_cast<{utype}>(b) & {mag};',
                  f'    if (x > {inf} || y > {inf}) return x > {inf} && y > {inf};',
                  f'    return x == 0 ? y == 0 : std::bit_cast<{utype}>(a) == std::bit_cast<{utype}>(b);',
                  '}']
    lines += ['inline bool same(bool a, bool b) noexcept { return a == b; }']
    names = []
    for k in kernels.values():
        for ctype in cpp.TYPES:
            f = interp.parse_format(FORMAT_OF[ctype])
            inputs, out = selftest_case(k, kernels, f)
            fn = f'{k.name}_{ctype}'
            lines += ['', f'// {k.name} ({ctype})']
            if out is None:
                lines.append(f'// not checked: its result depends on the contraction of a muladd')
                continue
            cases = [(fn, f'{k.name} ({ctype})', inputs, out)]
            special = nonfinite_case(k, kernels, f)
            if special:
                cases.append((f'{k.name}_nonfinite_{ctype}', f'{k.name} ({ctype}, a non-finite operand)')
                             + special)
            ins = [('bool' if kind == ir.MASK else ctype) for kind in k.input_kinds]
            outs = [('bool' if kind == ir.MASK else ctype) for kind in k.output_kinds]
            for fn, label, inputs, out in cases:
                names.append(fn)
                lines.append(f'inline const char* {fn}() noexcept {{')
                for i, (t, v) in enumerate(zip(ins, inputs)):
                    lines.append(f'    volatile {t} i{i} = {_value(v, ctype)};')
                for i, t in enumerate(outs):
                    lines.append(f'    {t} o{i};')
                args = [f'i{i}' for i in range(len(ins))] + [f'o{i}' for i in range(len(outs))]
                lines.append(f'    {k.name}({", ".join(args)});')
                cond = ' || '.join(f'!same(o{i}, {_value(v, ctype)})' for i, v in enumerate(out))
                lines += [f'    return {cond} ? "{label}" : nullptr;', '}']
    lines += ['', '// Each check in turn: the name of the first kernel whose result differs, or nullptr. The',
              '// checks are called through pointers so that each stays a function of its own, which keeps',
              '// the compile time of a translation unit that calls run() small.',
              'inline const char* run() noexcept {',
              '    using check = const char* (*)() noexcept;',
              '    static constexpr check checks[] = {']
    lines += [f'        {fn},' for fn in names]
    lines += ['    };', '    for (check c : checks)', '        if (const char* failed = c()) return failed;',
              '    return nullptr;', '}', '', '}  // namespace kairn::gen::selftest', 'KAIRN_GEN_POP_WARNINGS']
    return '\n'.join(lines) + '\n'
