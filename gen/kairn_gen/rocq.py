"""The Rocq printer: proofs/gen/Model.v, Statements.v and Audit.v (architecture.md, "The formal model").

This printer and the C++ printer are the trusted part of the generator: nothing proves that the
model printed here and the code printed there describe the same computation. Both are therefore a
table of spellings plus a loop over the kernel's statements, and the meaning of each spelling is
in the comment beside it.

It prints the real model only. A kernel without a real-model statement (a full kernel or a
constructor of the non-finite layer, ir.Kernel.real_model) is left out of all three files; a kernel
of the extended domain that has one is printed as before, its requirement canonical read as
normalized, which is the same thing for finite operands (and a ball, as a normalized center and a
nonnegative radius). The IEEE model and its statements are printed by ieee.py.

The model is Flocq's: rnd is rounding to nearest with tie rule `choice` in FLT_exp emin prec, the
format of precision prec with gradual underflow below 2^emin and no overflow. Every operation of
the IR is one application of rnd, except the exact ones. Calls stay calls. A mask is a bool.

Closing the section abstracts each definition over the section variables it uses, and only those
(lt_2_2 uses none and takes four reals). `section_args` follows the same rule, so that a statement
applies each kernel to exactly the arguments it has.
"""
from . import consts, expr, ir

# Logical paths: proofs/_CoqProject maps proofs/theories to Kairn; proofs/gen is Kairn.Gen.
GEN_PATH = 'Kairn.Gen'
THEORIES_PATH = 'Kairn'

# Each operation as a term of type R (or bool, for masks). {0} {1} {2} are operands, {f} the
# boolean that says whether the compiler fused a muladd.
SPELL = {
    'add': 'rnd ({0} + {1})',
    'sub': 'rnd ({0} - {1})',
    'neg': '- {0}',                                    # exact
    'abs': 'Rabs {0}',                                 # exact
    'fma': 'rnd ({0} * {1} + {2})',                    # one rounding
    'fms': 'rnd ({0} * {1} + - {2})',
    'fnma': 'rnd (- ({0} * {1}) + {2})',
    'prod': 'rnd ({0} * {1} + 0)',                     # C++: fma(a, b, +0.0)
    'muladd': 'if {f} then rnd ({0} * {1} + {2}) else rnd (rnd ({0} * {1}) + {2})',
    'lt': 'Rlt_bool {0} {1}',
    'le': 'Rle_bool {0} {1}',
    'eq': 'Req_bool {0} {1}',
    'and': 'andb {0} {1}',
    'or': 'orb {0} {1}',
    'not': 'negb {0}',
    'select': 'if {0} then {1} else {2}',
    'succ': 'succ radix2 (FLT_exp emin prec) {0}',     # the next number of the format
    'pred': 'pred radix2 (FLT_exp emin prec) {0}',
    'copy': '{0}',
    'guard': 'rnd ({0} + 0)',                          # the value of {0} (rule R3)
}

# The section variables each operation uses: those of rnd, or of the format alone.
USES = dict.fromkeys(('add', 'sub', 'fma', 'fms', 'fnma', 'prod', 'muladd', 'guard'),
                     ('emin', 'prec', 'choice'))
USES.update(succ=('emin', 'prec'), pred=('emin', 'prec'))
SECTION = ('emin', 'prec', 'choice')

# The constants of ir.CONSTANTS, as Rocq definitions over the section's prec.
CONSTANTS = {
    'splitter': ('Veltkamp\'s multiplier 2^ceil(prec/2) + 1.',
                 'bpow radix2 (Z.div (prec + 1) 2) + 1'),
}

# Names a value or a kernel must not take, because the printed text uses them: a let-bound
# `prec` would silently change what every later `rnd` means.
RESERVED = frozenset('''
    as at cofix else end exists exists2 fix for forall fun if in let match mod return then using
    where with is struct from
    rnd round radix2 bpow emin prec choice succ pred andb orb negb true false pow
    fmt RN RD RU u eta tie_even normalized_2 normalized_3 normalized_4 generic_format
    Rabs Rlt_bool Rle_bool Req_bool Znearest Zfloor Zceil FLT_exp R Z Prop Set Type bool
    rel tiny s_ xadd xmul xrd xru xsucc xpred
'''.split()) | frozenset(CONSTANTS)

HEADER = '(* Generated by gen/kairn-gen from gen/kernels/*.kernel. Do not edit. *)'


def _const_name(name, ups=None):
    """unit_computed(add_2_2) is the definition unit_computed_add_2_2; up(EXPR) is named by
    up_names; 0 is the real 0."""
    if ups and name in ups:
        return ups[name]
    c = ir.computed(name)
    return f'{c[0]}_{c[1]}' if c else name


def _operand(a, ups=None):
    return _const_name(a.name, ups) if a.const else a.name


def up_names(kernels):
    """{up(EXPR): the name of its definition}, one per distinct constant, named after the first
    kernel that uses it and its place among that kernel's distinct up constants: up_K_0, up_K_1,
    ... (so the third constant of a kernel is up_K_2 even when the first two are named after an
    earlier kernel)."""
    names = {}
    for k in kernels.values():
        mine = []
        for st in k.body:
            for a in st.args:
                if a.const and ir.up(a.name) is not None and a.name not in mine:
                    mine.append(a.name)
        for i, name in enumerate(mine):
            names.setdefault(name, f'up_{k.name}_{i}')
    return names


def _fuse(name):
    return f'fuse_{name}'


def _type(kind):
    return 'bool' if kind == ir.MASK else 'R'


def _binders(names, kinds):
    """(x0 x1 : R) (m : bool): consecutive values of one type share a binder."""
    out = []
    for v, kind in zip(names, kinds):
        if out and out[-1][1] == kind:
            out[-1][0].append(v)
        else:
            out.append(([v], kind))
    return ''.join(f' ({" ".join(vs)} : {_type(kind)})' for vs, kind in out)


def section_args(k, kernels):
    """The section variables the closed definition of k takes, in their order of declaration."""
    used = set()
    for st in k.body:
        used.update(section_args(kernels[st.op], kernels) if st.is_call else USES.get(st.op, ()))
        for a in st.args:
            if a.const and a.name in CONSTANTS:
                used.add('prec')
            elif a.const and (ir.computed(a.name) or ir.up(a.name) is not None):
                used.update(('emin', 'prec'))
    return [v for v in SECTION if v in used]


def definition(k, kernels, ups=None):
    """One kernel as a Definition over R (and bool, for masks), inside the section of Model.v."""
    ups = up_names(real(kernels)) if ups is None else ups
    sites = ir.muladd_sites(k, kernels)
    params = f' ({" ".join(map(_fuse, sites))} : bool)' if sites else ''
    params += _binders(k.input_limbs, k.input_kinds)
    lines = [f'(* {k.name}: {k.source or "no source given"}. *)',
             f'Definition {k.name}{params} : {" * ".join(map(_type, k.output_kinds))} :=']
    for st in k.body:
        args = [_operand(a, ups) for a in st.args]
        if st.is_call:
            # The callee's muladd choices are the caller's, under their inlined names.
            fuses = [_fuse(f'{st.dsts[0]}_{s}') for s in ir.muladd_sites(kernels[st.op], kernels)]
            pattern = st.dsts[0] if len(st.dsts) == 1 else "'(" + ', '.join(st.dsts) + ')'
            lines.append(f'  let {pattern} := {" ".join([st.op] + fuses + args)} in')
        else:
            lines.append(f'  let {st.dsts[0]} := {SPELL[st.op].format(*args, f=_fuse(st.dsts[0]))} in')
    outs = k.output_limbs
    lines.append(f'  {outs[0]}.' if len(outs) == 1 else f'  ({", ".join(outs)}).')
    return lines


def _computed_definition(name, kernels):
    """unit_computed(K) or tiny_computed(K) over the reals: consts.py's computation, stated."""
    fn, kname = ir.computed(name)
    e = consts.source_bound(kernels[kname])
    u = 'bpow radix2 (- prec)'
    rel = f'{_term(expr.parse(e["c"]), lambda n: u)} * {u} ^ {e["k"]}'
    tiny = f'{_term(expr.parse(e["t"]), None)} * bpow radix2 emin'
    what = 'rel / (1 - rel)' if fn == 'unit_computed' else 'tiny / (1 - rel)'
    lines = [f'(* {fn}({kname}): {what}, rounded up to the format, for the bound',
             f'   rel |v| + tiny of {kname}, with rel = c u^k and tiny = t eta from its claims. *)',
             f'Definition {_const_name(name)} : R :=',
             f'  let rel := {rel} in']
    if fn == 'unit_computed':
        lines.append('  round radix2 (FLT_exp emin prec) Zceil (rel / (1 - rel)).')
    else:
        lines += [f'  let tiny := {tiny} in',
                  '  round radix2 (FLT_exp emin prec) Zceil (tiny / (1 - rel)).']
    return lines


U_TERM = 'bpow radix2 (- prec)'
ETA_TERM = 'bpow radix2 emin'


def _up_definition(name, rocq_name, kernels):
    """up(EXPR) over the reals: EXPR rounded up to the format (consts.py's computation, stated),
    with unit(K) = c u^k and tiny(K) = t eta from K's error claim."""
    text = ir.up(name)

    def call(fn, kname):
        e = consts.source_bound(kernels[kname])
        if fn == 'unit':
            return f'({_term(expr.parse(e["c"]), lambda n: U_TERM)} * {U_TERM} ^ {e["k"]})'
        return f'({_term(expr.parse(e["t"]), None)} * {ETA_TERM})'

    term = _term(consts.up_tree(text), lambda n: {'u': U_TERM, 'eta': ETA_TERM}[n], call)
    # A name alone (up(eta)) is an application, `bpow radix2 emin`: the argument of round needs
    # parentheses; every compound term has them already.
    return [f'(* up({text}): the smallest number of the format not below it. *)',
            f'Definition {rocq_name} : R :=',
            f'  round radix2 (FLT_exp emin prec) Zceil {_paren(term)}.']


def real(kernels):
    """The kernels that have a real-model statement, in order."""
    return {name: k for name, k in kernels.items() if k.real_model}


def model(kernels):
    kernels = real(kernels)
    used = {a.name for k in kernels.values() for st in k.body for a in st.args if a.const} - {ir.ZERO}
    lines = [HEADER, '',
             '(* The formal model of every kernel: one function over the real numbers, in which every',
             '   operation is rounded once by rnd, Flocq\'s rounding to nearest with tie rule `choice` in',
             '   the format of precision prec with gradual underflow below 2^emin. The format has no',
             '   overflow: this wave\'s statements assume none. A call stays a call, so that a proof can',
             '   use the callee\'s theorem. A muladd takes one boolean argument, fuse_V for the value V it',
             '   defines, saying whether the compiler fused it. *)',
             'From Stdlib Require Import Reals ZArith.',
             'From Flocq Require Import Core.',
             'Open Scope R_scope.',
             '',
             'Section Kernels.',
             'Variable emin prec : Z.',
             'Variable choice : Z -> bool.',
             'Notation rnd := (round radix2 (FLT_exp emin prec) (Znearest choice)).']
    ups = up_names(kernels)
    # The constants by name, those defined by an expression last, in the order of their names.
    for name in sorted(used, key=lambda n: (1, ups[n]) if n in ups else (0, n)):
        if name in CONSTANTS:
            comment, term = CONSTANTS[name]
            lines += ['', f'(* {comment} *)', f'Definition {name} : R := {term}.']
        elif name in ups:
            lines += [''] + _up_definition(name, ups[name], kernels)
        else:
            lines += [''] + _computed_definition(name, kernels)
    for k in kernels.values():
        lines += [''] + definition(k, kernels, ups)
    lines += ['', 'End Kernels.']
    return '\n'.join(lines) + '\n'


def _term(tree, name, call=None, limb=None):
    """An expression tree of expr.py as a term over R; `name` spells a name, `call` a unit(K) or
    tiny(K), `limb` limb I of a group (the conditions of exact_when). An integer power is Rocq's
    pow, whose exponent is a natural number."""
    kind = tree[0]
    if kind == 'int':
        return str(tree[1])
    if kind == 'name':
        return name(tree[1])
    if kind == 'limb':
        return limb(tree[1], tree[2])
    if kind == 'call':
        return call(tree[1], tree[2])
    if kind == 'neg':
        return f'(- {_term(tree[1], name, call, limb)})'
    if kind == 'abs':
        # Rabs takes one argument: a name that is spelled as an application (`val cx`, a one-limb
        # input in the IEEE model) is put in parentheses; every other term already is, or is atomic.
        inner = _term(tree[1], name, call, limb)
        if ' ' in inner and not inner.startswith('('):
            inner = f'({inner})'
        return f'(Rabs {inner})'
    if kind == 'pow':
        base = f'({_term(tree[1], name, call, limb)} ^ {abs(tree[2])})'
        return base if tree[2] >= 0 else f'(/ {base})'
    op = {'add': '+', 'sub': '-', 'mul': '*', 'div': '/'}[kind]
    return f'({_term(tree[1], name, call, limb)} {op} {_term(tree[2], name, call, limb)})'


def _sum(limbs):
    return limbs[0] if len(limbs) == 1 else '(' + ' + '.join(limbs) + ')'


def _normalized(limbs):
    return f'normalized_{len(limbs)} emin prec {" ".join(limbs)}' if len(limbs) > 1 \
        else f'fmt emin prec {limbs[0]}'


VOCABULARY = '''\
(* Ties to even, in the form Flocq's Znearest expects: given the integer just below a midpoint,
   whether to round up. *)
Definition tie_even (n : Z) : bool := negb (Z.even n).

Section Vocabulary.
Variable emin prec : Z.

(* x is a number of the format: x = m 2^q with |m| < 2^prec and q >= emin. *)
Definition fmt (x : R) : Prop := generic_format radix2 (FLT_exp emin prec) x.

(* Rounding to the nearest number of the format, ties to even. *)
Definition RN (x : R) : R := round radix2 (FLT_exp emin prec) (Znearest tie_even) x.

(* The unit roundoff and the smallest positive number. *)
Definition u : R := bpow radix2 (- prec).
Definition eta : R := bpow radix2 emin.
'''

VOCABULARY_DIRECTED = '''\
(* Rounding down and up: the largest number of the format not above x, the smallest not below. *)
Definition RD (x : R) : R := round radix2 (FLT_exp emin prec) Zfloor x.
Definition RU (x : R) : R := round radix2 (FLT_exp emin prec) Zceil x.
'''


def _normalized_definition(n):
    xs = [f'x{i}' for i in range(n)]
    parts = [f'fmt {x}' for x in xs] + [f'x{i} = RN (x{i} + x{i + 1})' for i in range(n - 1)]
    return [f'(* A {n}-limb number is normalized: its limbs are numbers of the format, and each',
            '   limb is the rounding of itself plus the next one. *)',
            f'Definition normalized_{n} ({" ".join(xs)} : R) : Prop :=',
            '  ' + ' /\\ '.join(parts) + '.']


# One function per kind of ensures entry: the proposition it adds to the statement. `s` holds
# what they share (see statement). Each kind's exact formal shape is settled with the proofs.

def _claim_normalized(e, s):
    return _normalized(s.outs[e['of']].limbs)


def _claim_leading_rounded(e, s):
    return f'{s.outs[e["of"]].limbs[0]} = RN emin prec {s.value}'


def _paren(t):
    return f'({t})' if ' ' in t and not t.startswith('(') else t


def exact_condition(conditions, term, threshold):
    """The conditions of an exact_when as one proposition, their conjunction: (E = 0 \\/ K < Rabs E)
    for zero_or_abs_gt, with <= for zero_or_abs_ge. `term` spells an expression over the inputs and
    their limbs, `threshold` the constant K. Shared with the IEEE-model printer."""
    parts = []
    for c in conditions:
        kind = next(x for x in ir.EXACT_CONDITIONS if x in c)
        e = term(c[kind])
        rel = '<' if kind == 'zero_or_abs_gt' else '<='
        parts.append(f'({e} = 0 \\/ {threshold(c["than"])} {rel} Rabs {_paren(e)})')
    return ' /\\ '.join(parts)


def _exact_condition(e, s):
    return exact_condition(e['exact_when'],
                           lambda text: _term(expr.parse(text), lambda n: _sum(s.ins[n].limbs),
                                              limb=lambda g, i: s.ins[g].limbs[i]),
                           lambda text: _term(expr.parse(text), lambda n: {'u': 'u prec', 'eta': 'eta emin'}[n]))


def _claim_error(e, s):
    limbs, value = s.outs[e['of']].limbs, s.value
    c, t = expr.parse(e['c']), expr.parse(e['t'])
    zero = ('int', 0)
    if c == zero and t == zero:
        bound = f'{_sum(limbs)} = {value}'   # an error bound of zero is an equality
    else:
        if e['form'] == 'R':
            rho = f'Rabs {value}'
        elif e['form'] == 'A':
            rho = '(' + ' + '.join(f'Rabs {_sum(g.limbs)}' for g in s.k.inputs) + ')'
        else:
            # Relative to the terms of the value: s+x*y gives |s| + |x*y|.
            rho = '(' + ' + '.join(f'Rabs {_paren(_term(x, lambda n: _sum(s.ins[n].limbs)))}'
                                   for x in terms(expr.parse(s.k.value))) + ')'
        parts = []
        if c != zero:
            parts.append(f'{_term(c, lambda n: "u prec")} * u prec ^ {e["k"]} * {rho}')
        if t != zero:
            parts.append(f'{_term(t, None)} * eta emin')
        bound = f'Rabs ({_sum(limbs)} - {value}) <= {" + ".join(parts)}'
    if e['when'] == 'product_large':
        bound = (f'(({value} = 0 \\/ bpow radix2 (2 * prec - 1) * eta emin <= Rabs {value}) ->'
                 f' {bound})')
    if 'exact_when' in e:
        # The error is zero when the conditions hold.
        bound += f' /\\\n  ({_exact_condition(e, s)} ->\n   {_sum(limbs)} = {value})'
    return bound


def _claim_rounded(e, s):
    rounding = {'nearest': 'RN', 'down': 'RD', 'up': 'RU'}[e['mode']]
    claim = f'{s.outs[e["of"]].limbs[0]} = {rounding} emin prec {s.value}'
    if e.get('when') == 'product_large':
        claim = (f'(({s.value} = 0 \\/ bpow radix2 (2 * prec - 1) * eta emin <= Rabs {s.value}) ->'
                 f' {claim})')
    return claim


def _claim_neighbor(e, s):
    """The next number of the format above (or below) the value: Flocq's succ (pred)."""
    step = {'up': 'succ', 'down': 'pred'}[e['side']]
    return f'{s.outs[e["of"]].limbs[0]} = {step} radix2 (FLT_exp emin prec) {s.value}'


def _claim_bound(e, s):
    """On its side of the value, and at most `steps` steps of the format beyond the directed
    rounding of the value: RD (RU) followed by that many applications of pred (succ)."""
    r, v = s.outs[e['of']].limbs[0], s.value
    below = e['side'] == 'below'
    t = f'{"RD" if below else "RU"} emin prec {v}'
    for _ in range(e['steps']):
        t = f'{"pred" if below else "succ"} radix2 (FLT_exp emin prec) ({t})'
    return f'{r} <= {v} /\\ {t} <= {r}' if below else f'{v} <= {r} /\\ {r} <= {t}'


def _claim_upper(e, s):
    """value <= r, and r - value <= gaps (r - pred r) when the entry has gaps; the value is the
    entry's own when it has one (the bound kernels of Milestone 2); under its mask when it has
    `if`."""
    r = s.outs[e['of']].limbs[0]
    value = _paren(s.constant_term(e['value'])) if 'value' in e else s.value
    parts = [f'{value} <= {r}']
    if 'gaps' in e:
        gaps = _term(expr.parse(e['gaps']), None)
        parts.append(f'{r} - {value} <= {gaps} * ({r} - pred radix2 (FLT_exp emin prec) {r})')
    claim = ' /\\ '.join(parts)
    return f'({e["if"]} = true -> {claim})' if 'if' in e else claim


def _claim_holds(e, s):
    """The relation between two expressions of the inputs and the constants, under a mask."""
    a, b = (s.constant_term(x) for x in e['args'])
    rel = {'lt': '<', 'le': '<=', 'eq': '='}[e['rel']]
    return f'({e["if"]} = true -> {a} {rel} {b})'


def _claim_predicate(e, s):
    relation = {'lt': 'Rlt_bool', 'le': 'Rle_bool', 'eq': 'Req_bool'}[e['rel']]
    a, b = (s.term(x) for x in e['args'])
    return f'{e["of"]} = {relation} {a} {b}'


# The name of the member of the output ball in the statement of exact_when on encloses: never a
# value name (those have no underscore), nor a ball's.
MEMBER = 's_'


def _claim_encloses(e, s):
    balls = e['balls']
    hyps = [f'Rabs ({b} - {_sum(s.ins[cr["center"]].limbs)}) <= {cr["radius"]} ->' for b, cr in balls.items()]
    target = s.term(e['set'], lambda n: n if n in balls else _sum(s.ins[n].limbs))
    center = _sum(s.outs[e['center']].limbs)
    claim = (f'(forall {" ".join(balls)} : R, {" ".join(hyps)} '
             f'Rabs ({target} - {center}) <= {e["radius"]})')
    if 'exact_when' in e:
        # When the conditions hold, the output ball is the set exactly: besides containing it, it
        # contains nothing else.
        inside = ' /\\ '.join(f'Rabs ({b} - {_sum(s.ins[cr["center"]].limbs)}) <= {cr["radius"]}'
                              for b, cr in balls.items())
        claim += (f' /\\\n  ({_exact_condition(e, s)} ->\n'
                  f'   forall {MEMBER} : R, Rabs ({MEMBER} - {center}) <= {e["radius"]} ->\n'
                  f'   exists {" ".join(balls)} : R, {inside} /\\ {MEMBER} = {target})')
    return claim


CLAIMS = {'normalized': _claim_normalized, 'leading_rounded': _claim_leading_rounded,
          'error': _claim_error, 'rounded': _claim_rounded, 'upper': _claim_upper,
          'predicate': _claim_predicate, 'encloses': _claim_encloses, 'neighbor': _claim_neighbor,
          'bound': _claim_bound, 'holds': _claim_holds}


def terms(tree):
    """The terms of an expression read as a sum: s+x*y gives s and x*y, a-b a and -b (as trees)."""
    if tree[0] == 'add':
        return terms(tree[1]) + terms(tree[2])
    if tree[0] == 'sub':
        return terms(tree[1]) + [('neg', t) for t in terms(tree[2])]
    return [tree]


def constant_call(fn, kname, kernels, u, eta):
    """unit(K) = c u^k and tiny(K) = t eta of K's error claim, as terms, with u and eta spelled."""
    e = consts.source_bound(kernels[kname])
    if fn == 'unit':
        return f'({_term(expr.parse(e["c"]), lambda n: u)} * {u} ^ {e["k"]})'
    return f'({_term(expr.parse(e["t"]), None)} * {eta})'


def _hypotheses(k, ins):
    """The requirements, and that every limb is a number of the format. A canonical operand is a
    normalized one in the real model, where every value is finite; a ball(c, r) is a normalized
    center (a number of the format, for one limb) and a nonnegative radius."""
    normalized = {r[1] for r in k.requires if r[0] in ('normalized', 'canonical', 'ball')}
    hyps = []
    for g in k.inputs:
        if g.kind == ir.MASK:
            continue
        if g.name in normalized and len(g.limbs) > 1:
            hyps.append(_normalized(g.limbs))
        else:
            hyps += [f'fmt emin prec {v}' for v in g.limbs]
    for r in k.requires:
        if r[0] == 'abs_ge':
            hyps.append(f'Rabs {_sum(ins[r[2]].limbs)} <= Rabs {_sum(ins[r[1]].limbs)}')
        elif r[0] == 'power_of_two':
            hyps.append(f'(exists n : Z, {r[1]} = bpow radix2 n)')
        elif r[0] == 'nonneg':
            hyps.append(f'0 <= {r[1]}')
        elif r[0] == 'ball':
            hyps.append(f'0 <= {r[2]}')
        elif r[0] == 'count':
            hyps.append(f'({r[1]} = 0 \\/ 1 <= {r[1]})')
        elif r[0] == 'format':           # format half: the format contains 1/2
            hyps.append('eta emin <= / 2')
    return hyps


def _output_formats(k):
    """That every output limb is a number of the format, unless a `normalized` claim says so.

    This is what makes statements compose. The hypotheses of every statement say `fmt` of each
    input limb (_hypotheses), so the conclusion says it of each output limb: otherwise the theorem
    of one kernel would not establish the hypotheses of the next one (the radius of a ball, the
    error term of two_sum, the parts of a split). A `normalized` claim on an output group already
    says it of the group's limbs, and a mask is not a number.
    """
    covered = {e['of'] for e in k.ensures if e['kind'] == 'normalized'}
    return [f'fmt emin prec {v}' for g in k.outputs if g.kind == ir.LIMB and g.name not in covered
            for v in g.limbs]


class _Shared:
    def __init__(self, k, kernels=None):
        self.k, self.kernels = k, kernels
        self.ins = {g.name: g for g in k.inputs}
        self.outs = {g.name: g for g in k.outputs}
        self.value = self.term(k.value) if k.value is not None else None

    def term(self, text, name=None):
        return _term(expr.parse(text), name or (lambda n: _sum(self.ins[n].limbs)))

    def constant_term(self, text):
        """An expression of the claims of Milestone 2: input names (the sum of their limbs), the
        one-limb outputs, u, eta, unit(K), tiny(K)."""
        def name(n):
            if n == 'u':
                return 'u prec'
            if n == 'eta':
                return 'eta emin'
            return _sum(self.ins[n].limbs) if n in self.ins else self.outs[n].limbs[0]
        return _term(expr.parse(text), name,
                     lambda fn, kname: constant_call(fn, kname, self.kernels, 'u prec', 'eta emin'))


def statement(k, kernels):
    """The Definition <kernel>_spec : Prop that the kernel's proof must have as its type.

    Built from the claims: the requirements become hypotheses, and the conclusion is a conjunction
    of the formats of the output limbs (_output_formats), in output order, then of the ensures
    entries. Its exact shape is being settled with the proofs, which is why it is all here.

    A `represents` entry next to others (neg_2, abs_2) is not printed: for finite operands it says
    what `normalized` with an exact `error` says (architecture.md, "Claims of the non-finite
    layer").
    """
    s = _Shared(k, kernels)
    hyps = _hypotheses(k, s.ins)
    claims = _output_formats(k) + [CLAIMS[e['kind']](e, s) for e in k.ensures if e['kind'] != 'represents']
    sites = ir.muladd_sites(k, kernels)
    outl = k.output_limbs
    pattern = outl[0] if len(outl) == 1 else "'(" + ', '.join(outl) + ')'
    section = [{'choice': 'tie_even'}.get(v, v) for v in section_args(k, kernels)]
    call = ' '.join([k.name] + section + [_fuse(site) for site in sites] + k.input_limbs)
    pmin = k.min_precision or 1
    note = '' if k.min_precision else ' Minimum precision not known yet.'
    lines = [f'(* {k.name}: {k.source or "no source given"}. Status: {k.status}.{note} *)',
             f'Definition {k.name}_spec : Prop :=',
             f'  forall emin prec : Z, ({pmin} <= prec)%Z ->']
    for kind in (ir.LIMB, ir.MASK):
        names = [v for v, kk in zip(k.input_limbs, k.input_kinds) if kk == kind]
        if names:
            lines.append(f'  forall {" ".join(names)} : {_type(kind)},')
    if sites:
        lines.append(f'  forall {" ".join(map(_fuse, sites))} : bool,')
    lines += [f'  {h} ->' for h in hyps]
    lines.append(f'  let {pattern} := {call} in')
    lines.append('  ' + ' /\\\n  '.join(claims) + '.')
    return lines


