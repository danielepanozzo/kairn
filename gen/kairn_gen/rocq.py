"""The Rocq printer: proofs/gen/Model.v, Statements.v and Audit.v (architecture.md, "The formal model").

This printer and the C++ printer are the trusted part of the generator: nothing proves that the
model printed here and the code printed there describe the same computation. Both are therefore a
table of spellings plus a loop over the kernel's statements, and the meaning of each spelling is
in the comment beside it.

It prints the real model only. A kernel without a real-model statement (a full kernel or a
constructor of the non-finite layer, ir.Kernel.real_model) is left out of all three files; a kernel
of the extended domain that has one is printed as before, its requirement canonical read as
normalized, which is the same thing for finite operands (and a ball, as a normalized center and a
nonnegative radius). The IEEE model and its statements are printed by ieee.py.

The model is Flocq's: rnd is rounding to nearest with tie rule `choice` in FLT_exp emin prec, the
format of precision prec with gradual underflow below 2^emin and no overflow. Every operation of
the IR is one application of rnd, except the exact ones. Calls stay calls. A mask is a bool.

Closing the section abstracts each definition over the section variables it uses, and only those
(lt_2_2 uses none and takes four reals). `section_args` follows the same rule, so that a statement
applies each kernel to exactly the arguments it has.
"""
from . import consts, expr, ir

# Logical paths: proofs/_CoqProject maps proofs/theories to Kairn; proofs/gen is Kairn.Gen.
GEN_PATH = 'Kairn.Gen'
THEORIES_PATH = 'Kairn'

# Each operation as a term of type R (or bool, for masks). {0} {1} {2} are operands, {f} the
# boolean that says whether the compiler fused a muladd.
SPELL = {
    'add': 'rnd ({0} + {1})',
    'sub': 'rnd ({0} - {1})',
    'neg': '- {0}',                                    # exact
    'abs': 'Rabs {0}',                                 # exact
    'fma': 'rnd ({0} * {1} + {2})',                    # one rounding
    'fms': 'rnd ({0} * {1} + - {2})',
    'fnma': 'rnd (- ({0} * {1}) + {2})',
    'prod': 'rnd ({0} * {1} + 0)',                     # C++: fma(a, b, +0.0)
    'muladd': 'if {f} then rnd ({0} * {1} + {2}) else rnd (rnd ({0} * {1}) + {2})',
    'lt': 'Rlt_bool {0} {1}',
    'le': 'Rle_bool {0} {1}',
    'eq': 'Req_bool {0} {1}',
    'and': 'andb {0} {1}',
    'or': 'orb {0} {1}',
    'not': 'negb {0}',
    'select': 'if {0} then {1} else {2}',
    'succ': 'succ radix2 (FLT_exp emin prec) {0}',     # the next number of the format
    'pred': 'pred radix2 (FLT_exp emin prec) {0}',
    'copy': '{0}',
    'guard': 'rnd ({0} + 0)',                          # the value of {0} (rule R3)
}

# The section variables each operation uses: those of rnd, or of the format alone.
USES = dict.fromkeys(('add', 'sub', 'fma', 'fms', 'fnma', 'prod', 'muladd', 'guard'),
                     ('emin', 'prec', 'choice'))
USES.update(succ=('emin', 'prec'), pred=('emin', 'prec'))
SECTION = ('emin', 'prec', 'choice')

# The constants of ir.CONSTANTS, as Rocq definitions over the section's prec.
CONSTANTS = {
    'splitter': ('Veltkamp\'s multiplier 2^ceil(prec/2) + 1.',
                 'bpow radix2 (Z.div (prec + 1) 2) + 1'),
}

# Names a value or a kernel must not take, because the printed text uses them: a let-bound
# `prec` would silently change what every later `rnd` means.
RESERVED = frozenset('''
    as at cofix else end exists exists2 fix for forall fun if in let match mod return then using
    where with is struct from
    rnd round radix2 bpow emin prec choice succ pred andb orb negb true false pow
    fmt RN RD RU u eta tie_even normalized_2 normalized_3 normalized_4 generic_format
    Rabs Rlt_bool Rle_bool Req_bool Znearest Zfloor Zceil FLT_exp R Z Prop Set Type bool
    rel tiny s_ xadd xmul xrd xru xsucc xpred
'''.split()) | frozenset(CONSTANTS)

HEADER = '(* Generated by gen/kairn-gen from gen/kernels/*.kernel. Do not edit. *)'


def _const_name(name, ups=None):
    """unit_computed(add_2_2) is the definition unit_computed_add_2_2; up(EXPR) is named by
    up_names; 0 is the real 0."""
    if ups and name in ups:
        return ups[name]
    c = ir.computed(name)
    return f'{c[0]}_{c[1]}' if c else name


def _operand(a, ups=None):
    return _const_name(a.name, ups) if a.const else a.name


def constant_record(kernels):
    """The record of the names of the constants up(EXPR) that the kernel set was loaded with
    (gen/constant_names.json for gen/kernels; ir.load_constant_names): {EXPR: name}. Empty for a
    set loaded without one (the kernels of the tests)."""
    return next((k.constant_names for k in kernels.values() if k.constant_names), {})


def up_names(kernels):
    """{up(EXPR): the name of its definition}, one per distinct constant. A constant the record
    names keeps that name (constant_record): hand-written proofs use it, and a kernel added later
    must not rename it. A constant the record does not have is named after the first kernel K that
    uses it and its place i among K's distinct up constants, up_K_i (so the third constant of a
    kernel is up_K_2 even when the first two are named after an earlier kernel), with the next
    place when that name is the record's for another constant; build then adds it to the record."""
    record = constant_record(kernels)
    taken = set(record.values())
    names = {}
    for k in kernels.values():
        mine = []
        for st in k.body:
            for a in st.args:
                if a.const and ir.up(a.name) is not None and a.name not in mine:
                    mine.append(a.name)
        for i, name in enumerate(mine):
            if name in names:
                continue
            if ir.up(name) in record:
                names[name] = record[ir.up(name)]
                continue
            while f'up_{k.name}_{i}' in taken:
                i += 1
            names[name] = f'up_{k.name}_{i}'
            taken.add(names[name])
    return names


def constant_names_file(kernels):
    """gen/constant_names.json: the record the kernels were loaded with, and the names of the
    constants of the kernels that it does not have yet (those of the real model, and those that only
    a kernel without a real-model statement uses, which the IEEE model defines). Nothing is removed
    from it, so that a name, once given, is never given to another constant."""
    record = dict(constant_record(kernels))
    for name, rname in up_names(kernels).items():
        record.setdefault(ir.up(name), rname)
    return ir.constant_names_text(record)


def up_trees(kernels):
    """{the parsed EXPR of a constant up(EXPR): the name of its definition}: how a claim names a
    constant as the format rounds it (up( ) inside the constants rel and abs, Milestone 2)."""
    return {consts.up_tree(ir.up(name)): rname for name, rname in up_names(kernels).items()}


def _fuse(name):
    return f'fuse_{name}'


def _type(kind):
    return 'bool' if kind == ir.MASK else 'R'


def _binders(names, kinds):
    """(x0 x1 : R) (m : bool): consecutive values of one type share a binder."""
    out = []
    for v, kind in zip(names, kinds):
        if out and out[-1][1] == kind:
            out[-1][0].append(v)
        else:
            out.append(([v], kind))
    return ''.join(f' ({" ".join(vs)} : {_type(kind)})' for vs, kind in out)


def section_args(k, kernels):
    """The section variables the closed definition of k takes, in their order of declaration."""
    used = set()
    for st in k.body:
        used.update(section_args(kernels[st.op], kernels) if st.is_call else USES.get(st.op, ()))
        for a in st.args:
            if a.const and a.name in CONSTANTS:
                used.add('prec')
            elif a.const and (ir.computed(a.name) or ir.up(a.name) is not None):
                used.update(('emin', 'prec'))
    return [v for v in SECTION if v in used]


def definition(k, kernels, ups=None):
    """One kernel as a Definition over R (and bool, for masks), inside the section of Model.v."""
    ups = up_names(kernels) if ups is None else ups
    sites = ir.muladd_sites(k, kernels)
    params = f' ({" ".join(map(_fuse, sites))} : bool)' if sites else ''
    params += _binders(k.input_limbs, k.input_kinds)
    lines = [f'(* {k.name}: {k.source or "no source given"}. *)',
             f'Definition {k.name}{params} : {" * ".join(map(_type, k.output_kinds))} :=']
    for st in k.body:
        args = [_operand(a, ups) for a in st.args]
        if st.is_call:
            # The callee's muladd choices are the caller's, under their inlined names.
            fuses = [_fuse(f'{st.dsts[0]}_{s}') for s in ir.muladd_sites(kernels[st.op], kernels)]
            pattern = st.dsts[0] if len(st.dsts) == 1 else "'(" + ', '.join(st.dsts) + ')'
            lines.append(f'  let {pattern} := {" ".join([st.op] + fuses + args)} in')
        else:
            lines.append(f'  let {st.dsts[0]} := {SPELL[st.op].format(*args, f=_fuse(st.dsts[0]))} in')
    outs = k.output_limbs
    lines.append(f'  {outs[0]}.' if len(outs) == 1 else f'  ({", ".join(outs)}).')
    return lines


def _computed_definition(name, kernels):
    """unit_computed(K) or tiny_computed(K) over the reals: consts.py's computation, stated."""
    fn, kname = ir.computed(name)
    e = consts.source_bound(kernels[kname])
    u = 'bpow radix2 (- prec)'
    rel = f'{_term(expr.parse(e["c"]), lambda n: u)} * {u} ^ {e["k"]}'
    tiny = f'{_term(expr.parse(e["t"]), None)} * bpow radix2 emin'
    what = 'rel / (1 - rel)' if fn == 'unit_computed' else 'tiny / (1 - rel)'
    lines = [f'(* {fn}({kname}): {what}, rounded up to the format, for the bound',
             f'   rel |v| + tiny of {kname}, with rel = c u^k and tiny = t eta from its claims. *)',
             f'Definition {_const_name(name)} : R :=',
             f'  let rel := {rel} in']
    if fn == 'unit_computed':
        lines.append('  round radix2 (FLT_exp emin prec) Zceil (rel / (1 - rel)).')
    else:
        lines += [f'  let tiny := {tiny} in',
                  '  round radix2 (FLT_exp emin prec) Zceil (tiny / (1 - rel)).']
    return lines


U_TERM = 'bpow radix2 (- prec)'
ETA_TERM = 'bpow radix2 emin'


def up_term(name, kernels, u_term=U_TERM, eta_term=ETA_TERM):
    """EXPR of a constant up(EXPR) as a term over R, with u and eta spelled as given and unit(K) =
    c u^k, tiny(K) = t eta from K's error claim. Shared with the IEEE model, which spells them in
    the IEEE format for a constant that Model.v has not."""
    def call(fn, kname):
        e = consts.source_bound(kernels[kname])
        if fn == 'unit':
            return f'({_term(expr.parse(e["c"]), lambda n: u_term)} * {u_term} ^ {e["k"]})'
        return f'({_term(expr.parse(e["t"]), None)} * {eta_term})'

    return _term(consts.up_tree(ir.up(name)), lambda n: {'u': u_term, 'eta': eta_term}[n], call)


def _up_definition(name, rocq_name, kernels):
    """up(EXPR) over the reals: EXPR rounded up to the format (consts.py's computation, stated),
    with unit(K) = c u^k and tiny(K) = t eta from K's error claim."""
    text = ir.up(name)
    term = up_term(name, kernels)
    # A name alone (up(eta)) is an application, `bpow radix2 emin`: the argument of round needs
    # parentheses; every compound term has them already.
    return [f'(* up({text}): the smallest number of the format not below it. *)',
            f'Definition {rocq_name} : R :=',
            f'  round radix2 (FLT_exp emin prec) Zceil {_paren(term)}.']


def real(kernels):
    """The kernels that have a real-model statement, in order."""
    return {name: k for name, k in kernels.items() if k.real_model}


def model(kernels):
    # The names of the constants, from every kernel: a constant that a kernel without a real-model
    # statement uses first is named the same here and in the IEEE model (the record names them all).
    ups = up_names(kernels)
    kernels = real(kernels)
    used = {a.name for k in kernels.values() for st in k.body for a in st.args if a.const} - {ir.ZERO}
    lines = [HEADER, '',
             '(* The formal model of every kernel: one function over the real numbers, in which every',
             '   operation is rounded once by rnd, Flocq\'s rounding to nearest with tie rule `choice` in',
             '   the format of precision prec with gradual underflow below 2^emin. The format has no',
             '   overflow: this wave\'s statements assume none. A call stays a call, so that a proof can',
             '   use the callee\'s theorem. A muladd takes one boolean argument, fuse_V for the value V it',
             '   defines, saying whether the compiler fused it. *)',
             'From Stdlib Require Import Reals ZArith.',
             'From Flocq Require Import Core.',
             'Open Scope R_scope.',
             '',
             'Section Kernels.',
             'Variable emin prec : Z.',
             'Variable choice : Z -> bool.',
             'Notation rnd := (round radix2 (FLT_exp emin prec) (Znearest choice)).']
    # The constants by name, those defined by an expression last, in the order of their names.
    for name in sorted(used, key=lambda n: (1, ups[n]) if n in ups else (0, n)):
        if name in CONSTANTS:
            comment, term = CONSTANTS[name]
            lines += ['', f'(* {comment} *)', f'Definition {name} : R := {term}.']
        elif name in ups:
            lines += [''] + _up_definition(name, ups[name], kernels)
        else:
            lines += [''] + _computed_definition(name, kernels)
    for k in kernels.values():
        lines += [''] + definition(k, kernels, ups)
    lines += ['', 'End Kernels.']
    return '\n'.join(lines) + '\n'


def _term(tree, name, call=None, limb=None, up=None):
    """An expression tree of expr.py as a term over R; `name` spells a name, `call` a unit(K) or
    tiny(K), `limb` limb I of a group (the conditions of exact_when), `up` a constant up(EXPR)
    inside a claim's constant (given the parsed EXPR). An integer power is Rocq's pow, whose
    exponent is a natural number."""
    def t(x):
        return _term(x, name, call, limb, up)
    kind = tree[0]
    if kind == 'int':
        return str(tree[1])
    if kind == 'name':
        return name(tree[1])
    if kind == 'limb':
        return limb(tree[1], tree[2])
    if kind == 'call':
        return call(tree[1], tree[2])
    if kind == 'up':
        return up(tree[1])
    if kind == 'inv':
        return f'(/ {t(tree[1])})'
    if kind == 'neg':
        return f'(- {t(tree[1])})'
    if kind == 'abs':
        # Rabs takes one argument: a name that is spelled as an application (`val cx`, a one-limb
        # input in the IEEE model) is put in parentheses; every other term already is, or is atomic.
        inner = t(tree[1])
        if ' ' in inner and not inner.startswith('('):
            inner = f'({inner})'
        return f'(Rabs {inner})'
    if kind == 'pow':
        base = f'({t(tree[1])} ^ {abs(tree[2])})'
        return base if tree[2] >= 0 else f'(/ {base})'
    op = {'add': '+', 'sub': '-', 'mul': '*', 'div': '/'}[kind]
    return f'({t(tree[1])} {op} {t(tree[2])})'


def claim_constant_term(text, kernels, emin):
    """A constant of a claim (rel or abs of outward, Milestone 2) as a term over R in a statement:
    u is `u prec`, eta `eta EMIN`, unit(K) and tiny(K) are c u^k and t eta of K's error claim, and
    up(EXPR) is the definition of that constant in Model.v, applied to EMIN and prec. Shared with the
    IEEE-model printer, which gives its own EMIN.

    Printed in the forms of the proofs' constants (Directed2.v, outward_rel and outward_abs), so
    that a theorem has the statement as its type by unfolding them: 1/X is Rocq's / X, and a tiny(K)
    that is zero (t = 0 in K's claim) is 0."""
    names = up_trees(kernels)

    def call(fn, kname):
        e = consts.source_bound(kernels[kname])
        if fn == 'unit':
            return f'({_term(expr.parse(e["c"]), lambda n: "u prec")} * u prec ^ {e["k"]})'
        t = expr.parse(e['t'])
        return '0' if t == ('int', 0) else f'({_term(t, None)} * eta {emin})'

    def up(sub):
        return f'{names[sub]} {emin} prec'

    def inverses(tree):
        if tree[0] == 'div' and tree[1] == ('int', 1):
            return ('inv', inverses(tree[2]))
        if tree[0] in ('add', 'sub', 'mul', 'div'):
            return (tree[0], inverses(tree[1]), inverses(tree[2]))
        if tree[0] in ('neg', 'abs'):
            return (tree[0], inverses(tree[1]))
        if tree[0] == 'pow':
            return ('pow', inverses(tree[1]), tree[2])
        return tree
    return _term(inverses(consts.claim_tree(text)), lambda n: {'u': 'u prec', 'eta': f'eta {emin}'}[n], call,
                 up=up)


def _sum(limbs):
    return limbs[0] if len(limbs) == 1 else '(' + ' + '.join(limbs) + ')'


def _normalized(limbs):
    return f'normalized_{len(limbs)} emin prec {" ".join(limbs)}' if len(limbs) > 1 \
        else f'fmt emin prec {limbs[0]}'


VOCABULARY = '''\
(* Ties to even, in the form Flocq's Znearest expects: given the integer just below a midpoint,
   whether to round up. *)
Definition tie_even (n : Z) : bool := negb (Z.even n).

Section Vocabulary.
Variable emin prec : Z.

(* x is a number of the format: x = m 2^q with |m| < 2^prec and q >= emin. *)
Definition fmt (x : R) : Prop := generic_format radix2 (FLT_exp emin prec) x.

(* Rounding to the nearest number of the format, ties to even. *)
Definition RN (x : R) : R := round radix2 (FLT_exp emin prec) (Znearest tie_even) x.

(* The unit roundoff and the smallest positive number. *)
Definition u : R := bpow radix2 (- prec).
Definition eta : R := bpow radix2 emin.
'''

VOCABULARY_DIRECTED = '''\
(* Rounding down and up: the largest number of the format not above x, the smallest not below. *)
Definition RD (x : R) : R := round radix2 (FLT_exp emin prec) Zfloor x.
Definition RU (x : R) : R := round radix2 (FLT_exp emin prec) Zceil x.
'''


def _normalized_definition(n):
    xs = [f'x{i}' for i in range(n)]
    parts = [f'fmt {x}' for x in xs] + [f'x{i} = RN (x{i} + x{i + 1})' for i in range(n - 1)]
    return [f'(* A {n}-limb number is normalized: its limbs are numbers of the format, and each',
            '   limb is the rounding of itself plus the next one. *)',
            f'Definition normalized_{n} ({" ".join(xs)} : R) : Prop :=',
            '  ' + ' /\\ '.join(parts) + '.']


# One function per kind of ensures entry: the proposition it adds to the statement. `s` holds
# what they share (see statement). Each kind's exact formal shape is settled with the proofs.

def _claim_normalized(e, s):
    return _normalized(s.outs[e['of']].limbs)


def _claim_leading_rounded(e, s):
    return f'{s.outs[e["of"]].limbs[0]} = RN emin prec {s.value}'


def _paren(t):
    return f'({t})' if ' ' in t and not t.startswith('(') else t


def exact_condition(conditions, term, threshold):
    """The conditions of an exact_when as one proposition, their conjunction: (E = 0 \\/ K < Rabs E)
    for zero_or_abs_gt, with <= for zero_or_abs_ge. `term` spells an expression over the inputs and
    their limbs, `threshold` the constant K. Shared with the IEEE-model printer."""
    parts = []
    for c in conditions:
        if ir.ZERO_CONDITION in c:
            # zero(EXPR) (Milestone 2, outward): EXPR = 0, written as the theorems write it.
            parts.append(f'{term(c[ir.ZERO_CONDITION])} = 0')
            continue
        kind = next(x for x in ir.EXACT_CONDITIONS if x in c)
        e = term(c[kind])
        rel = '<' if kind == 'zero_or_abs_gt' else '<='
        parts.append(f'({e} = 0 \\/ {threshold(c["than"])} {rel} Rabs {_paren(e)})')
    return ' /\\ '.join(parts)


def _exact_condition(e, s):
    return exact_condition(e['exact_when'],
                           lambda text: _term(expr.parse(text), lambda n: _sum(s.ins[n].limbs),
                                              limb=lambda g, i: s.ins[g].limbs[i]),
                           lambda text: _term(expr.parse(text), lambda n: {'u': 'u prec', 'eta': 'eta emin'}[n]))


def _claim_error(e, s):
    limbs, value = s.outs[e['of']].limbs, s.value
    c, t = expr.parse(e['c']), expr.parse(e['t'])
    zero = ('int', 0)
    if c == zero and t == zero:
        bound = f'{_sum(limbs)} = {value}'   # an error bound of zero is an equality
    else:
        if e['form'] == 'R':
            rho = f'Rabs {value}'
        elif e['form'] == 'A':
            rho = '(' + ' + '.join(f'Rabs {_sum(g.limbs)}' for g in s.k.inputs) + ')'
        else:
            # Relative to the terms of the value: s+x*y gives |s| + |x*y|.
            rho = '(' + ' + '.join(f'Rabs {_paren(_term(x, lambda n: _sum(s.ins[n].limbs)))}'
                                   for x in terms(expr.parse(s.k.value))) + ')'
        parts = []
        if c != zero:
            parts.append(f'{_term(c, lambda n: "u prec")} * u prec ^ {e["k"]} * {rho}')
        if t != zero:
            parts.append(f'{_term(t, None)} * eta emin')
        bound = f'Rabs ({_sum(limbs)} - {value}) <= {" + ".join(parts)}'
    if e['when'] == 'product_large':
        bound = (f'(({value} = 0 \\/ bpow radix2 (2 * prec - 1) * eta emin <= Rabs {value}) ->'
                 f' {bound})')
    if 'exact_when' in e:
        # The error is zero when the conditions hold.
        bound += f' /\\\n  ({_exact_condition(e, s)} ->\n   {_sum(limbs)} = {value})'
    return bound


def _claim_rounded(e, s):
    rounding = {'nearest': 'RN', 'down': 'RD', 'up': 'RU'}[e['mode']]
    if 'value' in e:
        # A value of its own, over the inputs and their limbs.
        v = _term(expr.parse(e['value']), lambda n: _sum(s.ins[n].limbs), limb=lambda g, i: s.ins[g].limbs[i])
        return f'{s.outs[e["of"]].limbs[0]} = {rounding} emin prec {_paren(v)}'
    claim = f'{s.outs[e["of"]].limbs[0]} = {rounding} emin prec {s.value}'
    if e.get('when') == 'product_large':
        claim = (f'(({s.value} = 0 \\/ bpow radix2 (2 * prec - 1) * eta emin <= Rabs {s.value}) ->'
                 f' {claim})')
    return claim


def _claim_neighbor(e, s):
    """The next number of the format above (or below) the value: Flocq's succ (pred)."""
    step = {'up': 'succ', 'down': 'pred'}[e['side']]
    return f'{s.outs[e["of"]].limbs[0]} = {step} radix2 (FLT_exp emin prec) {s.value}'


def _claim_bound(e, s):
    """On its side of the value, and at most `steps` steps of the format beyond the directed
    rounding of the value: RD (RU) followed by that many applications of pred (succ)."""
    r, v = s.outs[e['of']].limbs[0], s.value
    below = e['side'] == 'below'
    t = f'{"RD" if below else "RU"} emin prec {v}'
    for _ in range(e['steps']):
        t = f'{"pred" if below else "succ"} radix2 (FLT_exp emin prec) ({t})'
    return f'{r} <= {v} /\\ {t} <= {r}' if below else f'{v} <= {r} /\\ {r} <= {t}'


def _claim_upper(e, s):
    """value <= r, and r - value <= gaps (r - pred r) when the entry has gaps; the value is the
    entry's own when it has one (the bound kernels of Milestone 2); under its mask when it has
    `if`."""
    r = s.outs[e['of']].limbs[0]
    value = _paren(s.constant_term(e['value'])) if 'value' in e else s.value
    parts = [f'{value} <= {r}']
    if 'gaps' in e:
        gaps = _term(expr.parse(e['gaps']), None)
        parts.append(f'{r} - {value} <= {gaps} * ({r} - pred radix2 (FLT_exp emin prec) {r})')
    claim = ' /\\ '.join(parts)
    return f'({e["if"]} = true -> {claim})' if 'if' in e else claim


def _claim_maximum(e, s):
    """The output is the larger of the two expressions, over the inputs and their limbs."""
    a, b = (_term(expr.parse(x), lambda n: _sum(s.ins[n].limbs), limb=lambda g, i: s.ins[g].limbs[i])
            for x in e['args'])
    return f'{s.outs[e["of"]].limbs[0]} = Rmax {_paren(a)} {_paren(b)}'


def _claim_holds(e, s):
    """The relation between two expressions of the inputs and the constants, under a mask."""
    a, b = (s.constant_term(x) for x in e['args'])
    rel = {'lt': '<', 'le': '<=', 'eq': '='}[e['rel']]
    return f'({e["if"]} = true -> {a} {rel} {b})'


def _claim_predicate(e, s):
    relation = {'lt': 'Rlt_bool', 'le': 'Rle_bool', 'eq': 'Req_bool'}[e['rel']]
    a, b = (s.term(x) for x in e['args'])
    return f'{e["of"]} = {relation} {a} {b}'


# The name of the member of the output ball in the statement of exact_when on encloses: never a
# value name (those have no underscore), nor a ball's.
MEMBER = 's_'


def _claim_encloses(e, s):
    balls = e['balls']
    hyps = [f'Rabs ({b} - {_sum(s.ins[cr["center"]].limbs)}) <= {cr["radius"]} ->' for b, cr in balls.items()]
    target = s.term(e['set'], lambda n: n if n in balls else _sum(s.ins[n].limbs))
    center = _sum(s.outs[e['center']].limbs)
    if not balls:
        # The operands are points (add_ball_2_2): the radius bounds the error of the center.
        return f'Rabs ({target} - {center}) <= {e["radius"]}'
    claim = (f'(forall {" ".join(balls)} : R, {" ".join(hyps)} '
             f'Rabs ({target} - {center}) <= {e["radius"]})')
    if 'exact_when' in e:
        # When the conditions hold, the output ball is the set exactly: besides containing it, it
        # contains nothing else.
        inside = ' /\\ '.join(f'Rabs ({b} - {_sum(s.ins[cr["center"]].limbs)}) <= {cr["radius"]}'
                              for b, cr in balls.items())
        claim += (f' /\\\n  ({_exact_condition(e, s)} ->\n'
                  f'   forall {MEMBER} : R, Rabs ({MEMBER} - {center}) <= {e["radius"]} ->\n'
                  f'   exists {" ".join(balls)} : R, {inside} /\\ {MEMBER} = {target})')
    return claim


def _claim_outward(e, s):
    """On its side of the value, within rel |value| + abs of it, the constants as the format rounds
    them (claim_constant_term); and the value itself when the conditions of exact_when hold (the
    shape of the theorems of Directed2.v)."""
    out, v = _sum(s.outs[e['of']].limbs), s.value
    side = f'{out} <= {v}' if e['side'] == 'below' else f'{v} <= {out}'
    rel = claim_constant_term(e['rel'], s.kernels, 'emin')
    absolute = claim_constant_term(e['abs'], s.kernels, 'emin')
    claim = f'{side} /\\\n  Rabs ({out} - {v}) <= {rel} * Rabs {v} + {absolute}'
    if 'exact_when' in e:
        claim += f' /\\\n  ({_exact_condition(e, s)} -> {out} = {v})'
    return claim


CLAIMS = {'normalized': _claim_normalized, 'leading_rounded': _claim_leading_rounded,
          'error': _claim_error, 'rounded': _claim_rounded, 'upper': _claim_upper,
          'predicate': _claim_predicate, 'encloses': _claim_encloses, 'neighbor': _claim_neighbor,
          'bound': _claim_bound, 'holds': _claim_holds, 'maximum': _claim_maximum,
          'outward': _claim_outward}


def terms(tree):
    """The terms of an expression read as a sum: s+x*y gives s and x*y, a-b a and -b (as trees)."""
    if tree[0] == 'add':
        return terms(tree[1]) + terms(tree[2])
    if tree[0] == 'sub':
        return terms(tree[1]) + [('neg', t) for t in terms(tree[2])]
    return [tree]


def constant_call(fn, kname, kernels, u, eta):
    """unit(K) = c u^k and tiny(K) = t eta of K's error claim, as terms, with u and eta spelled."""
    e = consts.source_bound(kernels[kname])
    if fn == 'unit':
        return f'({_term(expr.parse(e["c"]), lambda n: u)} * {u} ^ {e["k"]})'
    return f'({_term(expr.parse(e["t"]), None)} * {eta})'


def _hypotheses(k, ins):
    """The requirements, and that every limb is a number of the format. A canonical operand is a
    normalized one in the real model, where every value is finite; a ball(c, r) is a normalized
    center (a number of the format, for one limb) and a nonnegative radius."""
    normalized = {r[1] for r in k.requires if r[0] in ('normalized', 'canonical', 'ball')}
    hyps = []
    for g in k.inputs:
        if g.kind == ir.MASK:
            continue
        if g.name in normalized and len(g.limbs) > 1:
            hyps.append(_normalized(g.limbs))
        else:
            hyps += [f'fmt emin prec {v}' for v in g.limbs]
    for r in k.requires:
        if r[0] == 'abs_ge':
            hyps.append(f'Rabs {_sum(ins[r[2]].limbs)} <= Rabs {_sum(ins[r[1]].limbs)}')
        elif r[0] == 'power_of_two':
            hyps.append(f'(exists n : Z, {r[1]} = bpow radix2 n)')
        elif r[0] == 'nonneg':
            hyps.append(f'0 <= {r[1]}')
        elif r[0] == 'ball':
            hyps.append(f'0 <= {r[2]}')
        elif r[0] == 'count':
            hyps.append(f'({r[1]} = 0 \\/ 1 <= {r[1]})')
        elif r[0] == 'format':           # format half: the format contains 1/2
            hyps.append('eta emin <= / 2')
    return hyps


def _output_formats(k):
    """That every output limb is a number of the format, unless a `normalized` claim says so.

    This is what makes statements compose. The hypotheses of every statement say `fmt` of each
    input limb (_hypotheses), so the conclusion says it of each output limb: otherwise the theorem
    of one kernel would not establish the hypotheses of the next one (the radius of a ball, the
    error term of two_sum, the parts of a split). A `normalized` claim on an output group already
    says it of the group's limbs, and a mask is not a number.
    """
    covered = {e['of'] for e in k.ensures if e['kind'] == 'normalized'}
    return [f'fmt emin prec {v}' for g in k.outputs if g.kind == ir.LIMB and g.name not in covered
            for v in g.limbs]


class _Shared:
    def __init__(self, k, kernels=None):
        self.k, self.kernels = k, kernels
        self.ins = {g.name: g for g in k.inputs}
        self.outs = {g.name: g for g in k.outputs}
        self.value = self.term(k.value) if k.value is not None else None

    def term(self, text, name=None):
        return _term(expr.parse(text), name or (lambda n: _sum(self.ins[n].limbs)))

    def constant_term(self, text):
        """An expression of the claims of Milestone 2: input names (the sum of their limbs), the
        one-limb outputs, u, eta, unit(K), tiny(K)."""
        def name(n):
            if n == 'u':
                return 'u prec'
            if n == 'eta':
                return 'eta emin'
            return _sum(self.ins[n].limbs) if n in self.ins else self.outs[n].limbs[0]
        return _term(expr.parse(text), name,
                     lambda fn, kname: constant_call(fn, kname, self.kernels, 'u prec', 'eta emin'))


def statement(k, kernels):
    """The Definition <kernel>_spec : Prop that the kernel's proof must have as its type.

    Built from the claims: the requirements become hypotheses, and the conclusion is a conjunction
    of the formats of the output limbs (_output_formats), in output order, then of the ensures
    entries. Its exact shape is being settled with the proofs, which is why it is all here.

    A `represents` entry next to others (neg_2, abs_2) is not printed: for finite operands it says
    what `normalized` with an exact `error` says (architecture.md, "Claims of the non-finite
    layer").
    """
    s = _Shared(k, kernels)
    hyps = _hypotheses(k, s.ins)
    claims = conclusion(k, kernels)
    sites = ir.muladd_sites(k, kernels)
    outl = k.output_limbs
    pattern = outl[0] if len(outl) == 1 else "'(" + ', '.join(outl) + ')'
    section = [{'choice': 'tie_even'}.get(v, v) for v in section_args(k, kernels)]
    call = ' '.join([k.name] + section + [_fuse(site) for site in sites] + k.input_limbs)
    pmin = k.min_precision or 1
    note = '' if k.min_precision else ' Minimum precision not known yet.'
    lines = [f'(* {k.name}: {k.source or "no source given"}. Status: {k.status}.{note} *)',
             f'Definition {k.name}_spec : Prop :=',
             f'  forall emin prec : Z, ({pmin} <= prec)%Z ->']
    for kind in (ir.LIMB, ir.MASK):
        names = [v for v, kk in zip(k.input_limbs, k.input_kinds) if kk == kind]
        if names:
            lines.append(f'  forall {" ".join(names)} : {_type(kind)},')
    if sites:
        lines.append(f'  forall {" ".join(map(_fuse, sites))} : bool,')
    lines += [f'  {h} ->' for h in hyps]
    lines.append(f'  let {pattern} := {call} in')
    lines.append('  ' + ' /\\\n  '.join(claims) + '.')
    return lines


def conclusion(k, kernels):
    """The conclusion of a kernel's statement, as a list of conjuncts over its limb names: the
    formats of the output limbs, then the claims (statement; a map's statement uses it entry by
    entry)."""
    s = _Shared(k, kernels)
    return _output_formats(k) + [CLAIMS[e['kind']](e, s) for e in k.ensures if e['kind'] != 'represents']


def statements(kernels):
    every = kernels      # for the names of the constants a claim names (claim_constant_term)
    kernels = real(kernels)
    sizes = sorted({len(g.limbs) for k in kernels.values() for g in k.inputs + k.outputs
                    if len(g.limbs) > 1})
    lines = [HEADER, '',
             '(* One statement per kernel, built from its claims (gen/claims.json): a hand-written proof',
             '   of kernel K is a theorem K_correct whose type is exactly K_spec. Rounding is to nearest,',
             '   ties to even, with gradual underflow and no overflow. A statement assumes that every',
             '   input limb is a number of the format, and concludes the same of every output limb (by',
             '   fmt, or by normalized), so that one statement gives the hypotheses of the next. *)',
             'From Stdlib Require Import Reals ZArith.',
             'From Flocq Require Import Core.',
             f'From {GEN_PATH} Require Import Model.',
             'Open Scope R_scope.',
             '',
             VOCABULARY,
             VOCABULARY_DIRECTED]
    for n in sizes:
        lines += _normalized_definition(n) + ['']
    lines.append('End Vocabulary.')
    for k in kernels.values():
        lines += [''] + statement(k, every)
    return '\n'.join(lines) + '\n'


# --- Folds -----------------------------------------------------------------------------------------
#
# The model of a fold (milestone2.md, "Folds, the extension of the IR") is written with the two
# functions on lists of proofs/theories/Folds.v and nothing else: the state is a tuple of limbs,
# an element one entry of every array as a tuple (a pair of pairs for two arrays of two limbs),
# the step and the combination are functions of those tuples that apply the kernels' models of
# Model.v to their limbs, and the zero state has every limb 0. A tuple is nested to the left, as
# Rocq writes (a, b, c), and read with fst and snd, so that a function of tuples that a theorem
# names (add22 of SummationKernels.v is add_2_2 of fst and snd) is the generated one by
# conversion. The finish, which says what comes out when the state is not finite, has no
# real-model statement: in the real model nothing is infinite, and the result is the final state.

def tuple_type(n, item='R'):
    return ' * '.join([item] * n) if n > 1 else item


def tuple_parts(term, n):
    """The n components of a left-nested tuple `term`, as terms: (a, b, c) is ((a, b), c)."""
    if n == 1:
        return [term]
    return tuple_parts(f'fst {_paren(term)}', n - 1) + [f'snd {_paren(term)}']


def fold_section_args(kernel_list, kernels):
    used = set()
    for k in kernel_list:
        used.update(section_args(k, kernels))
    return [v for v in SECTION if v in used]


def _apply(k, kernels, args, section=None):
    """The model of kernel k applied to the section variables it takes and to `args`."""
    head = [k.name] + (section_args(k, kernels) if section is None else section)
    return ' '.join(head + [_paren(a) for a in args])


def fold_element_type(fd):
    """The type of an element: the tuple of the arrays' groups, (R * R) * (R * R) for dot_2."""
    types = [tuple_type(len(g.limbs)) for g in fd.arrays]
    if len(types) == 1:
        return types[0]
    return ' * '.join(f'({t})' if ' ' in t else t for t in types)


def fold_groups(fd, element):
    """{array name: the term of its group in the element `element`}."""
    parts = tuple_parts(element, len(fd.arrays))
    return {g.name: p for g, p in zip(fd.arrays, parts)}


def state_type(fd, real='R', mask='bool'):
    """The type of a fold's state: the tuple of its limbs, R * R for two limbs, R * bool for a limb
    and a mask (a fold of maxima)."""
    return ' * '.join(mask if kind == ir.MASK else real for kind in fd.state_kinds())


def state_zero(fd, zero, true):
    """The zero state: every limb `zero`, every mask `true`, as a tuple."""
    parts = [true if kind == ir.MASK else zero for kind in fd.state_kinds()]
    return parts[0] if len(parts) == 1 else '(' + ', '.join(parts) + ')'


def state_groups(fd, state):
    """{state group name: the terms of its limbs in the state tuple `state`}."""
    parts = tuple_parts(state, len(fd.state_limbs()))
    out, at = {}, 0
    for g in fd.states:
        out[g.name] = parts[at:at + len(g.limbs)]
        at += len(g.limbs)
    return out


def fold_model(kernels):
    """proofs/gen/FoldModel.v: every fold's step, combination and two orders."""
    folds = getattr(kernels, 'folds', {})
    lines = [HEADER, '',
             '(* The formal model of every fold (docs/developer/architecture.md, "Folds"): a loop of kernels',
             '   along arrays, in the two orders of proofs/theories/Folds.v. The state is a tuple of limbs and',
             '   an element one entry of every array as a tuple, each read with fst and snd; the step and the',
             '   combination apply the models of their kernels (Model.v) to those limbs; the zero state has',
             '   every limb 0. F_seq is fold_seq of the step from the zero state, F_lanes W fold_lanes of the',
             '   step and the combination with W lanes. The finish of a fold has no real-model statement and',
             '   is not here: in the real model nothing is infinite, and the result is the final state. *)',
             'From Stdlib Require Import Reals ZArith List.',
             'From Flocq Require Import Core.',
             f'From {GEN_PATH} Require Import Model.',
             f'From {THEORIES_PATH} Require Import Folds.',
             'Open Scope R_scope.',
             '']
    if any(fd.is_conv for fd in folds.values()):
        lines += CONV_LISTS + ['']
    lines += ['Section Folds.',
              'Variable emin prec : Z.',
              'Variable choice : Z -> bool.']
    # A convolution names the sequential order of the fold of its coefficients: after the others.
    for fd in [fd for fd in folds.values() if not fd.is_conv] + [fd for fd in folds.values() if fd.is_conv]:
        if fd.is_map:
            lines += map_model(fd, kernels)
            continue
        if fd.is_conv:
            lines += conv_model(fd, kernels)
            continue
        if fd.is_bv:
            lines += bv_model(fd, kernels)
            continue
        step, combine = kernels[fd.step[0]], kernels[fd.combine[0]] if fd.combine else None
        st, el, _ = _fold_binders(fd)
        stype = state_type(fd)
        etype = fold_element_type(fd)
        zero = state_zero(fd, '0', 'true')
        groups = fold_groups(fd, el)
        groups.update(state_groups(fd, st))
        sizes = {g.name: len(g.limbs) for g in fd.arrays}
        args = []
        for a in fd.step[1]:
            args += groups[a] if a in fd.state_names() else tuple_parts(groups[a], sizes[a])
        arrays = ', '.join(f'{fd.roles[g.name]} {g.name}' for g in fd.arrays)
        if len(fd.states) == 1:
            what = f'state {fd.state.name} of {len(fd.state.limbs)} limb{"s" if len(fd.state.limbs) > 1 else ""}'
        else:
            what = 'state ' + ', '.join(f'{g.name} (a {"mask" if g.kind == ir.MASK else "limb"})' for g in fd.states)
        lines += ['', f'(* {fd.name}: arrays {arrays}; {what}; step {step.name}'
                      + (f', combination {combine.name}' if combine else '') + '. *)',
                  f'Definition {fd.name}_step ({st} : {stype}) ({el} : {etype}) : {stype} :=',
                  f'  {_apply(step, kernels, args)}.']
        if combine is not None:
            n = len(fd.state_limbs())
            lines += ['', f'Definition {fd.name}_combine (a b : {stype}) : {stype} :=',
                      f'  {_apply(combine, kernels, tuple_parts("a", n) + tuple_parts("b", n))}.']
        lt = f'list ({etype})' if ' ' in etype else f'list {etype}'
        if 'sequential' in fd.orders:
            lines += ['', f'Definition {fd.name}_seq (xs : {lt}) : {stype} :=',
                      f'  fold_seq {fd.name}_step {zero} xs.']
        if 'lanes' in fd.orders:
            lines += ['', f'Definition {fd.name}_lanes (W : nat) (xs : {lt}) : {stype} :=',
                      f'  fold_lanes {fd.name}_step {fd.name}_combine {zero} W xs.']
    lines += ['', 'End Folds.']
    return '\n'.join(lines) + '\n'


def _fold_binders(fd):
    element = ''.join(g.name for g in fd.arrays)
    return ''.join(fd.state_names()), element, element + 's'


def _fold_term(text, groups, fd):
    """The value of an element (an expression over the arrays' names) as a term: each name the
    sum of the limbs of its group."""
    sizes = {g.name: len(g.limbs) for g in fd.arrays}
    return _term(expr.parse(text), lambda n: _sum(tuple_parts(groups[n], sizes[n])))


def _height(h, xs):
    return {'n': f'length {xs}', 'n-1': f'(length {xs} - 1)'}[h]


def _constants(text):
    return _term(expr.parse(text), lambda n: {'u': 'u prec', 'eta': 'eta emin'}[n])


def fold_statement(fd, kernels, order):
    """The Definition F_seq_spec or F_lanes_spec : Prop, from the fold's claims: for every list of
    valid elements, the result is valid and within the bound of fold_error, with the powers of
    the bound (the forms with gamma, which need a hypothesis on n, follow from these by
    pow_minus_1_le_gamma of Summation.v)."""
    st, el, xs = _fold_binders(fd)
    suffix = ir.ORDER_SUFFIX[order]
    step, combine, _ = (kernels[c[0]] if c else None for c in (fd.step, fd.combine, fd.finish))
    parts = [step] + ([combine] if order == 'lanes' else [])
    section = [{'choice': 'tie_even'}.get(v, v) for v in fold_section_args(parts, kernels)]
    etype = fold_element_type(fd)
    lt = f'list ({etype})' if ' ' in etype else f'list {etype}'
    groups = fold_groups(fd, el)
    normalized = {r[1] for r in fd.requires if r[0] in ('normalized', 'canonical')}
    valid = []
    for g in fd.arrays:
        limbs = tuple_parts(groups[g.name], len(g.limbs))
        if g.name in normalized:
            valid.append(f'normalized_{len(limbs)} emin prec {" ".join(_paren(x) for x in limbs)}')
        else:
            valid += [f'fmt emin prec {_paren(x)}' for x in limbs]
    claims = fold_conclusion(fd, st, el, xs)
    binders = f'forall (W : nat) ({xs} : {lt}),' if order == 'lanes' else f'forall {xs} : {lt},'
    call = ' '.join([f'{fd.name}_{suffix}'] + section + (['W'] if order == 'lanes' else []) + [xs])
    what = {'sequential': 'the sequential order', 'lanes': 'the lane order, for every number of lanes W'}[order]
    lines = [f'(* {fd.name}, {what}: {fd.source or "no source given"}. Status: {fd.status}. *)',
             f'Definition {fd.name}_{suffix}_spec : Prop :=',
             f'  forall emin prec : Z, ({fd.min_precision} <= prec)%Z ->',
             f'  {binders}',
             f'  Forall (fun {el} => {" /\\ ".join(valid)}) {xs} ->',
             f'  let {st} := {call} in',
             '  ' + ' /\\\n  '.join(claims) + '.']
    return lines


def max_steps(fd):
    """The number of steps up of the result of a fold of maxima from the limb of its final state
    (the claim upper ... steps=S, which rules.py checks against its finish)."""
    return next(e['steps'] for e in fd.ensures if e['kind'] == 'upper' and e.get('over') == 'max')


def max_result(fd, st, emin='emin'):
    """The result of a fold of maxima from the term `st` of its final state: its limb, stepped up
    as many times as the finish does (succ, Flocq's)."""
    r = tuple_parts(st, len(fd.state_limbs()))[0]
    for _ in range(max_steps(fd)):
        r = f'succ radix2 (FLT_exp {emin} prec) {_paren(r)}'
    return r


def max_conclusion(fd, r, el, xs, emin='emin'):
    """The conclusion of the statement of a fold of maxima: with v_ the largest value of an element
    (fold_right Rmax from 0), the result `r` (a term, let-bound to r_ by the caller) is a number of
    the format, at least v_, and at most RU(v_) stepped up S times (upper ... max steps=S). Returns
    (the let lines, the conjuncts)."""
    groups = fold_groups(fd, el)
    value = f'(fun {el} => {_fold_term(fd.value, groups, fd)})'
    limit = f'RU {emin} prec v_'
    for _ in range(max_steps(fd)):
        limit = f'succ radix2 (FLT_exp {emin} prec) ({limit})'
    lets = [f'let r_ := {r} in', f'let v_ := fold_right Rmax 0 (map {value} {xs}) in']
    return lets, [f'fmt {emin} prec r_', 'v_ <= r_', f'r_ <= {limit}']


def max_statement(fd, kernels, order):
    """F_seq_spec or F_lanes_spec of a fold of maxima, from its claims: for every list of valid
    elements, the result computed from the final state (max_result) is a number of the format
    between the largest value of an element and that value rounded up then stepped up S times."""
    st, el, xs = _fold_binders(fd)
    suffix = ir.ORDER_SUFFIX[order]
    step, combine = kernels[fd.step[0]], kernels[fd.combine[0]] if fd.combine else None
    parts = [step] + ([combine] if order == 'lanes' else [])
    section = [{'choice': 'tie_even'}.get(v, v) for v in fold_section_args(parts, kernels)]
    etype = fold_element_type(fd)
    lt = f'list ({etype})' if ' ' in etype else f'list {etype}'
    groups = fold_groups(fd, el)
    normalized = {r[1] for r in fd.requires if r[0] in ('normalized', 'canonical')}
    valid = []
    for g in fd.arrays:
        limbs = tuple_parts(groups[g.name], len(g.limbs))
        if g.name in normalized:
            valid.append(f'normalized_{len(limbs)} emin prec {" ".join(_paren(x) for x in limbs)}')
        else:
            valid += [f'fmt emin prec {_paren(x)}' for x in limbs]
    lets, claims = max_conclusion(fd, max_result(fd, st), el, xs)
    binders = f'forall (W : nat) ({xs} : {lt}),' if order == 'lanes' else f'forall {xs} : {lt},'
    call = ' '.join([f'{fd.name}_{suffix}'] + section + (['W'] if order == 'lanes' else []) + [xs])
    what = {'sequential': 'the sequential order', 'lanes': 'the lane order, for every number of lanes W'}[order]
    return [f'(* {fd.name}, {what}: {fd.source or "no source given"}. Status: {fd.status}. *)',
            f'Definition {fd.name}_{suffix}_spec : Prop :=',
            f'  forall emin prec : Z, ({fd.min_precision} <= prec)%Z ->',
            f'  {binders}',
            f'  Forall (fun {el} => {" /\\ ".join(valid)}) {xs} ->',
            f'  let {st} := {call} in'] + [f'  {x}' for x in lets] + [
            '  ' + ' /\\\n  '.join(claims) + '.']


def fold_conclusion(fd, st, el, xs, indent='    '):
    """The conclusion of a fold's statement over the real model, a list of conjuncts: the final
    state `st` (a term) is valid and within the bound of fold_error, over the list of elements `xs`
    (a term), `el` the binder of an element. The IEEE-model statement (ieee.py) says the same of the
    values of its result."""
    groups = fold_groups(fd, el)
    n = len(fd.state.limbs)
    result = tuple_parts(st, n)
    covered = any(e['kind'] == 'normalized' for e in fd.ensures)
    claims = [f'normalized_{n} emin prec {" ".join(_paren(x) for x in result)}'] if covered else \
        [f'fmt emin prec {_paren(x)}' for x in result]
    value = f'(fun {el} => {_fold_term(fd.value, groups, fd)})'
    for e in fd.ensures:
        if e['kind'] != 'fold_error':
            continue
        eps = _constants(e['eps'])
        power = f'(1 + {eps}) ^ {_height(e["rel"], xs)}'
        if expr.parse(e['term']) != ('int', 0):
            power = f'(1 + {_constants(e["term"])}) * {power}'
        bound = f'({power} - 1) * sumabs (map {value} {xs})'
        if expr.parse(e['tau']) != ('int', 0):
            bound += (f' +\n{indent}(1 + {eps}) ^ {_height(e["abs"], xs)} * (INR (length {xs}) * '
                      f'{_constants(e["tau"])})')
        claims.append(f'Rabs ({_sum(result)} - sumR (map {value} {xs})) <=\n{indent}{bound}')
    return claims


def fold_statements(kernels):
    """proofs/gen/FoldStatements.v: the statements of every fold, in each of its orders."""
    lines = [HEADER, '',
             '(* One statement per fold and order, built from the fold\'s claims (gen/claims.json, "folds"):',
             '   a hand-written proof of fold F in order O is a theorem F_O_correct whose type is exactly',
             '   F_O_spec. For every list of elements that satisfy the requirements, every limb a number of',
             '   the format, the result is valid and within the bound, in the form with the powers of',
             '   proofs/theories/Summation.v (sumR, sumabs); the lane order for every number of lanes. Rounding',
             '   is to nearest, ties to even, with gradual underflow and no overflow, as in Statements.v. *)',
             'From Stdlib Require Import Reals ZArith List.',
             'From Flocq Require Import Core.',
             f'From {GEN_PATH} Require Import Model Statements FoldModel.',
             f'From {THEORIES_PATH} Require Import Folds Summation.',
             'Open Scope R_scope.']
    for fd in getattr(kernels, 'folds', {}).values():
        if fd.is_map:
            lines += [''] + map_statement(fd, kernels)
            continue
        if fd.is_bv:
            lines += [''] + bv_statement(fd, kernels)
            continue
        if fd.is_conv:
            lines += [''] + conv_statement(fd, kernels)
            continue
        for order in ir.ORDERS:
            if order in fd.orders:
                lines += [''] + (max_statement if fd.is_max else fold_statement)(fd, kernels, order)
    return '\n'.join(lines) + '\n'


# --- Maps --------------------------------------------------------------------------------------------
#
# A map (rules.py, "Maps") is in the real model the function `map` of its step on the list of
# elements: no state, since every written element depends on its element and the scalars alone,
# and the mask that says what is finite has no real-model meaning (nothing is infinite there). The
# lane order and the sequential one write the same elements, so the model has no order. Its
# statement says, entry by entry (Forall2 of the list of elements and the list written), what the
# step's statement concludes, under the map's requirements on every element and on the scalars.

def map_model(fd, kernels):
    """The step of a map, as a function of its scalars and of one element, and the map."""
    step = kernels[fd.step[0]]
    _, el, xs = _fold_binders(fd)
    etype = fold_element_type(fd)
    lt = f'list ({etype})' if ' ' in etype else f'list {etype}'
    groups = fold_groups(fd, el)
    sizes = {g.name: len(g.limbs) for g in fd.arrays + fd.scalars}
    groups.update({g.name: g.name for g in fd.scalars})
    args = [p for a in fd.step[1] for p in tuple_parts(groups[a], sizes[a])]
    params = ''.join(f' ({g.name} : {tuple_type(len(g.limbs))})' for g in fd.scalars)
    written = fd.writes[0]
    wtype = tuple_type(len(written.limbs))
    arrays = ', '.join(f'{fd.roles[g.name]} {g.name}' for g in fd.arrays)
    scalars = ', '.join(f'{fd.roles[g.name]} {g.name}' for g in fd.scalars)
    return ['', f'(* {fd.name}: a map; arrays {arrays}' + (f'; scalars {scalars}' if scalars else '') +
            f'; it writes {written.name} by the step {step.name}. *)',
            f'Definition {fd.name}_step{params} ({el} : {etype}) : {wtype} :=',
            f'  {_apply(step, kernels, args)}.',
            '',
            f'Definition {fd.name}_map{params} ({xs} : {lt}) : list {_paren(wtype)} :=',
            f'  map ({fd.name}_step{"".join(" " + g.name for g in fd.scalars)}) {xs}.']


def _pattern(parts):
    """The pattern of a left-nested tuple of names or patterns: a name alone, or (a, b, c), which
    Rocq reads as ((a, b), c)."""
    return parts[0] if len(parts) == 1 else '(' + ', '.join(parts) + ')'


def _let(pattern, term):
    return f"let '{pattern} := {term} in" if pattern.startswith('(') else f'let {pattern} := {term} in'


def map_statement(fd, kernels):
    """The Definition F_spec : Prop of a map: for all scalars and lists of elements that satisfy
    the map's requirements, every limb a number of the format, each written element satisfies the
    conclusion of the step's statement for its element (Forall2)."""
    step = kernels[fd.step[0]]
    _, el, xs = _fold_binders(fd)
    section = [{'choice': 'tie_even'}.get(v, v) for v in fold_section_args([step], kernels)]
    etype = fold_element_type(fd)
    lt = f'list ({etype})' if ' ' in etype else f'list {etype}'
    # The step's own names for what the map passes it: its input groups, in the order of the call.
    kgroup = dict(zip(fd.step[1], step.inputs))
    normalized = {r[1] for r in fd.requires if r[0] in ('normalized', 'canonical')}
    pow2 = {r[1] for r in fd.requires if r[0] == 'power_of_two'}

    def valid(g, limbs):
        if g.name in normalized:
            return [f'normalized_{len(limbs)} emin prec {" ".join(_paren(x) for x in limbs)}']
        return [f'fmt emin prec {_paren(x)}' for x in limbs] + \
            [f'(exists n : Z, {limbs[0]} = bpow radix2 n)' for _ in [0] if g.name in pow2]

    scalar_limbs = [v for g in fd.scalars for v in kgroup[g.name].limbs]
    hyps = [h for g in fd.scalars for h in valid(g, list(kgroup[g.name].limbs))]
    groups = fold_groups(fd, el)
    element = [h for g in fd.arrays for h in valid(g, tuple_parts(groups[g.name], len(g.limbs)))]
    pattern = _pattern([_pattern(list(kgroup[g.name].limbs)) for g in fd.arrays])
    outs = step.outputs[0].limbs
    claims = conclusion(step, kernels)
    scalars = ' '.join('(' + ', '.join(kgroup[g.name].limbs) + ')' if len(g.limbs) > 1 else kgroup[g.name].limbs[0]
                       for g in fd.scalars)
    call = ' '.join([f'{fd.name}_map'] + section + ([scalars] if scalars else []) + [xs])
    binders = (f'forall ({" ".join(scalar_limbs)} : R) ({xs} : {lt}),' if scalar_limbs
               else f'forall {xs} : {lt},')
    lines = [f'(* {fd.name}, each element it writes: {fd.source or "no source given"}. Status: {fd.status}. *)',
             f'Definition {fd.name}_spec : Prop :=',
             f'  forall emin prec : Z, ({fd.min_precision} <= prec)%Z ->',
             f'  {binders}']
    lines += [f'  {h} ->' for h in hyps]
    lines += [f'  Forall (fun {el} => {" /\\ ".join(element)}) {xs} ->',
              f'  Forall2 (fun {el} w_ =>']
    lines += [f'    {_let(pattern, el)}'] if pattern != el else []
    lines += [f'    {_let(_pattern(list(outs)), "w_")}',
              '    ' + ' /\\\n    '.join(claims) + ')',
              f'    {xs} ({call}).']
    return lines


# --- Ball vectors ------------------------------------------------------------------------------------
#
# A ball vector (rules.py, "Ball vectors") is in the real model the map of its step on the elements,
# the centers written, and its radius: the radius kernel on the limb of the sequential fold of the
# record (the step of a fold of maxima) over the centers written, from (0, true), and on the scalars.
# Its statement says that every center written is valid and that the ball of each center with the
# one radius contains the value of every choice of members of the operands' balls, entry by entry.

def bv_scalar_params(fd, names, item='R'):
    return ''.join(f' ({g.name} : {tuple_type(len(g.limbs), item)})' for g in fd.scalars if g.name in names)


def bv_model(fd, kernels):
    """F_step and F_map (the centers), F_record (the state's update from a center written) and
    F_radius (the one radius) of a ball vector."""
    step, record, radius = (kernels[c[0]] for c in (fd.step, fd.record, fd.radius))
    _, el, xs = _fold_binders(fd)
    etype = fold_element_type(fd)
    lt = f'list ({etype})' if ' ' in etype else f'list {etype}'
    groups = fold_groups(fd, el)
    sizes = {g.name: len(g.limbs) for g in fd.arrays + fd.scalars}
    groups.update({g.name: g.name for g in fd.scalars})
    args = [p for a in fd.step[1] for p in tuple_parts(groups[a], sizes[a])]
    used = set(fd.step[1])
    params = bv_scalar_params(fd, used)
    written = fd.writes[0]
    wtype = tuple_type(len(written.limbs))
    stype = state_type(fd)
    zero = state_zero(fd, '0', 'true')
    mok = ''.join(fd.state_names())
    rec_args = tuple_parts(mok, 2) + tuple_parts('w_', len(written.limbs))
    stepped = f'({fd.name}_step{"".join(" " + g.name for g in fd.scalars if g.name in used)})' \
        if used & {g.name for g in fd.scalars} else f'{fd.name}_step'
    rad_args = [f'(fst (fold_seq {fd.name}_record {zero} ({fd.name}_map'
                f'{"".join(" " + g.name for g in fd.scalars if g.name in used)} {xs})))'] + list(fd.radius[1][1:])
    arrays = ', '.join(f'{fd.roles[g.name]} {g.name}' for g in fd.arrays)
    scalars = ', '.join(f'{fd.roles[g.name]} {g.name}' for g in fd.scalars)
    return ['', f'(* {fd.name}: a ball vector; arrays {arrays}; scalars {scalars}; it writes {written.name} by the '
                f'step {step.name}, records the largest magnitude of a center by {record.name}, and gives the radius '
                f'by {radius.name}. *)',
            f'Definition {fd.name}_step{params} ({el} : {etype}) : {wtype} :=',
            f'  {_apply(step, kernels, args)}.',
            '',
            f'Definition {fd.name}_map{params} ({xs} : {lt}) : list {_paren(wtype)} :=',
            f'  map {stepped} {xs}.',
            '',
            f'Definition {fd.name}_record ({mok} : {stype}) (w_ : {wtype}) : {stype} :=',
            f'  {_apply(record, kernels, rec_args)}.',
            '',
            f'Definition {fd.name}_radius{bv_scalar_params(fd, {g.name for g in fd.scalars})} ({xs} : {lt}) : R :=',
            f'  {_apply(radius, kernels, rad_args)}.']


def bv_member(name):
    """The binder of a member of the ball of an operand, named after its array: x_ for x."""
    return f'{name}_'


def bv_statement(fd, kernels):
    """The Definition F_spec : Prop of a ball vector: for nonnegative radii and valid centers (every
    limb a number of the format), the radius is a number of the format and, entry by entry (Forall2 of
    the elements and the centers written), the center written is valid and, for every choice of
    members of the balls of the operands' entries, the value of the fold on them is within the radius
    of the center."""
    if fd.ensures[0]['kind'] == 'makes_ball_vector':
        return bv_make_statement(fd, kernels)
    step, radius = kernels[fd.step[0]], kernels[fd.radius[0]]
    _, el, xs = _fold_binders(fd)
    section = [{'choice': 'tie_even'}.get(v, v) for v in fold_section_args([step, radius, kernels[fd.record[0]]],
                                                                             kernels)]
    etype = fold_element_type(fd)
    lt = f'list ({etype})' if ' ' in etype else f'list {etype}'
    vectors = {r[1]: r[2] for r in fd.requires if r[0] == 'ball_vector'}
    radii = set(vectors.values())
    scalar_limbs = [v for g in fd.scalars for v in g.limbs]
    hyps = []
    for g in fd.scalars:
        hyps += [f'fmt emin prec {v}' for v in g.limbs]
        if g.name in radii:
            hyps.append(f'0 <= {g.name}')
    groups = fold_groups(fd, el)
    valid = []
    for g in fd.arrays:
        limbs = tuple_parts(groups[g.name], len(g.limbs))
        valid += ([f'normalized_{len(limbs)} emin prec {" ".join(_paren(x) for x in limbs)}'] if len(limbs) > 1
                  else [f'fmt emin prec {_paren(limbs[0])}'])
    pattern = _pattern([_pattern(list(g.limbs)) for g in fd.arrays])
    w = list(fd.writes[0].limbs)
    entry = fd.ensures[0]
    members = [bv_member(b) for b in entry['balls']]
    near = [f'Rabs ({bv_member(b)} - {_sum(next(g for g in fd.arrays if g.name == v["center"]).limbs)}) <= {v["radius"]}'
            for b, v in entry['balls'].items()]

    def name(n):
        if n in entry['balls']:
            return bv_member(n)
        return _sum(next(g for g in fd.scalars if g.name == n).limbs)
    setv = _term(expr.parse(entry['set']), name)
    center = (f'normalized_{len(w)} emin prec {" ".join(w)}' if len(w) > 1 else f'fmt emin prec {w[0]}')
    used = [g.name for g in fd.scalars if g.name in fd.step[1]]
    call_map = ' '.join([f'{fd.name}_map'] + [{'choice': 'tie_even'}.get(v, v) for v in fold_section_args([step], kernels)]
                        + used + [xs])
    call_r = ' '.join([f'{fd.name}_radius'] + section + [g.name for g in fd.scalars] + [xs])
    lines = [f'(* {fd.name}, each center it writes and its one radius: {fd.source or "no source given"}. '
             f'Status: {fd.status}. *)',
             f'Definition {fd.name}_spec : Prop :=',
             f'  forall emin prec : Z, ({fd.min_precision} <= prec)%Z ->',
             f'  forall ({" ".join(scalar_limbs)} : R) ({xs} : {lt}),']
    lines += [f'  {h} ->' for h in hyps]
    lines += [f'  Forall (fun {el} => {" /\\ ".join(valid)}) {xs} ->',
              f'  let r_ := {call_r} in',
              '  fmt emin prec r_ /\\',
              f'  Forall2 (fun {el} w_ =>']
    lines += [f'    {_let(pattern, el)}'] if pattern != el else []
    lines += [f'    {_let(_pattern(w), "w_")}',
              f'    {center} /\\',
              f'    forall {" ".join(members)} : R, ' + ' -> '.join(near) + f' -> Rabs ({setv} - {_sum(w)}) <= r_)',
              f'    {xs} ({call_map}).']
    return lines


def bv_make_statement(fd, kernels):
    """The Definition F_spec : Prop of a constructor of a BallVector (makes_ball_vector): in the real
    model, where nothing is infinite and the radius given is a number of the format, for valid centers
    (every limb a number of the format, normalized for two limbs) the centers written are those given
    and the radius is the radius given, exactly."""
    step, radius = kernels[fd.step[0]], kernels[fd.radius[0]]
    _, el, xs = _fold_binders(fd)
    section = [{'choice': 'tie_even'}.get(v, v) for v in fold_section_args([step, radius, kernels[fd.record[0]]],
                                                                             kernels)]
    etype = fold_element_type(fd)
    lt = f'list ({etype})' if ' ' in etype else f'list {etype}'
    c, r = fd.arrays[0], fd.scalars[0]
    limbs = tuple_parts(el, len(c.limbs))
    valid = (f'normalized_{len(limbs)} emin prec {" ".join(_paren(x) for x in limbs)}' if len(limbs) > 1
             else f'fmt emin prec {_paren(limbs[0])}')
    call_map = ' '.join([f'{fd.name}_map'] + [{'choice': 'tie_even'}.get(v, v) for v in fold_section_args([step], kernels)]
                        + [xs])
    call_r = ' '.join([f'{fd.name}_radius'] + section + [r.name, xs])
    return [f'(* {fd.name}, the centers it writes and its radius: {fd.source or "no source given"}. Status: '
            f'{fd.status}. *)',
            f'Definition {fd.name}_spec : Prop :=',
            f'  forall emin prec : Z, ({fd.min_precision} <= prec)%Z ->',
            f'  forall ({r.name} : R) ({xs} : {lt}),',
            f'  fmt emin prec {r.name} ->',
            f'  Forall (fun {el} => {valid}) {xs} ->',
            f'  {call_r} = {r.name} /\\',
            f'  Forall2 (fun {el} w_ => w_ = {el}) {xs} ({call_map}).']


# --- Convolutions ------------------------------------------------------------------------------------
#
# A convolution (rules.py, "Convolutions") is in the real model the list of its coefficients, each the
# sequential order of the fold of its coefficients on the list of its terms. The terms of coefficient
# j are built by stdlib's list functions (conv_terms), and the number of coefficients by conv_length,
# both printed once before the section, since they are about lists only.

CONV_LISTS = [
    '(* The terms of coefficient j of the product of the polynomials xs and ys: the pairs (x_i, y_(j-i))',
    '   for max(0, j - (length ys - 1)) <= i <= min(j, length xs - 1), in increasing i. The entries of xs',
    '   from that i on, among the first j + 1, against those of ys from j - i down, the first j + 1 of ys',
    '   reversed; combine stops at the shorter list, which is the first. *)',
    'Definition conv_terms {A B : Type} (xs : list A) (ys : list B) (j : nat) : list (A * B) :=',
    '  combine (skipn (j - (length ys - 1)) (firstn (S j) xs)) (rev (firstn (S j) ys)).',
    '',
    '(* The number of coefficients of the product: length xs + length ys - 1, none when a polynomial',
    '   is empty. *)',
    'Definition conv_length (nx ny : nat) : nat :=',
    '  match nx, ny with',
    '  | O, _ | _, O => O',
    '  | _, _ => (nx + ny - 1)%nat',
    '  end.']


def conv_model(fd, kernels):
    """A convolution: the map of the sequential order of the fold of its coefficients on the terms
    of each coefficient."""
    cf = kernels.folds[fd.coefficients]
    x, y = fd.arrays
    tx, ty = tuple_type(len(x.limbs)), tuple_type(len(y.limbs))
    lx = f'list ({tx})' if ' ' in tx else f'list {tx}'
    ly = f'list ({ty})' if ' ' in ty else f'list {ty}'
    st = state_type(cf)
    lw = f'list ({st})' if ' ' in st else f'list {st}'
    xs, ys = f'{x.name}s', f'{y.name}s'
    return ['', f'(* {fd.name}: a convolution; arrays {fd.roles[x.name]} {x.name}, {fd.roles[y.name]} {y.name}; '
                f'coefficient j is {cf.name} in the sequential order on conv_terms {xs} {ys} j; it writes '
                f'{fd.writes[0].name}. *)',
            f'Definition {fd.name}_conv ({xs} : {lx}) ({ys} : {ly}) : {lw} :=',
            f'  map (fun j => {cf.name}_seq (conv_terms {xs} {ys} j)) (seq 0 (conv_length (length {xs}) (length {ys}))).']


def conv_statement(fd, kernels):
    """The Definition F_spec : Prop of a convolution: for all lists of valid entries of the two
    arrays, every limb a number of the format, each coefficient satisfies, on its own terms, the
    conclusion of the statement of the fold of its coefficients in the sequential order (Forall2 of
    the indices of the coefficients and the coefficients)."""
    cf = kernels.folds[fd.coefficients]
    x, y = fd.arrays
    st, el, txs = _fold_binders(cf)
    section = [{'choice': 'tie_even'}.get(v, v) for v in fold_section_args([kernels[cf.step[0]]], kernels)]
    xs, ys = f'{x.name}s', f'{y.name}s'
    normalized = {r[1] for r in fd.requires if r[0] in ('normalized', 'canonical')}
    hyps = []
    for g, l in ((x, xs), (y, ys)):
        limbs = tuple_parts(g.name, len(g.limbs))
        valid = ([f'normalized_{len(limbs)} emin prec {" ".join(_paren(v) for v in limbs)}'] if g.name in normalized
                 else [f'fmt emin prec {_paren(v)}' for v in limbs])
        hyps.append(f'Forall (fun {g.name} => {" /\\ ".join(valid)}) {l}')
    tx = tuple_type(len(x.limbs))
    lx = f'list ({tx})' if ' ' in tx else f'list {tx}'
    ty = tuple_type(len(y.limbs))
    ly = f'list ({ty})' if ' ' in ty else f'list {ty}'
    binders = f'forall ({xs} : {lx}) ({ys} : {ly}),' if lx != ly else f'forall {xs} {ys} : {lx},'
    claims = fold_conclusion(cf, st, el, txs, indent='      ')
    call = ' '.join([f'{fd.name}_conv'] + section + [xs, ys])
    lines = [f'(* {fd.name}, each coefficient it writes: {fd.source or "no source given"}. Status: {fd.status}. *)',
             f'Definition {fd.name}_spec : Prop :=',
             f'  forall emin prec : Z, ({fd.min_precision} <= prec)%Z ->',
             f'  {binders}']
    lines += [f'  {h} ->' for h in hyps]
    lines += [f'  Forall2 (fun j {st} =>',
              f'    let {txs} := conv_terms {xs} {ys} j in',
              '    ' + ' /\\\n    '.join(claims) + ')',
              f'    (seq 0 (conv_length (length {xs}) (length {ys}))) ({call}).']
    return lines


def theory_module(path):
    """proofs/theories/A/B.v -> A.B"""
    return path[len('proofs/theories/'):-len('.v')].replace('/', '.')


def audit(kernels):
    verified = [k for k in real(kernels).values() if k.status != 'unverified']
    # The folds that are proved: each order's theorem, as for a kernel (FoldStatements.v is
    # imported only when there is one, so that the file is what it was before folds existed).
    folds = [fd for fd in getattr(kernels, 'folds', {}).values() if fd.status != 'unverified']
    lines = [HEADER, '',
             '(* For every kernel not marked unverified: its theorem has exactly the generated',
             '   statement as its type, and the axioms it depends on are printed, for the audit',
             '   script to compare with the allow-list. Nothing else is printed. *)',
             f'From {GEN_PATH} Require Import Statements.']
    if folds:
        lines.append(f'From {GEN_PATH} Require Import FoldStatements.')
    for m in sorted({theory_module(k.theorem[0]) for k in verified} | {theory_module(fd.theorem) for fd in folds}):
        lines.append(f'From {THEORIES_PATH} Require Import {m}.')
    if not verified and not folds:
        lines += ['', '(* No kernel is verified yet. *)']
    for k in verified:
        lines += ['', f'Definition {k.name}_audit : {k.name}_spec := {k.name}_correct.',
                  f'Print Assumptions {k.name}_correct.']
    for fd in folds:
        # A map and a convolution have one statement each, F_spec, not one per order.
        names = [fd.name] if fd.is_map or fd.is_conv or fd.is_bv else \
            [f'{fd.name}_{ir.ORDER_SUFFIX[order]}' for order in ir.ORDERS if order in fd.orders]
        for name in names:
            lines += ['', f'Definition {name}_audit : {name}_spec := {name}_correct.',
                      f'Print Assumptions {name}_correct.']
    return '\n'.join(lines) + '\n'
