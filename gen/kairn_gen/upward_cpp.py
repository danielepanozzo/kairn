# The header.

def _description(k):
    def group(g):
        if g.name in k.pair_inputs or g.name in k.pair_outputs:
            return f'pair {g.name} = ({", ".join(g.limbs)})'
        return f'mask {g.name}' if g.kind == ir.MASK else g.name
    sig = f"{k.name}({', '.join(map(group, _groups(k, 'input')))}) -> {', '.join(map(group, _groups(k, 'output')))}"
    what = 'rounds upward' if _rounds(k) else 'exact'
    return [f'// {sig}: {what}.', f'// {k.source or "no source given"}. Status: {k.ieee_status} (IEEE model only).']


