# The self-check's cases: fixed operands of every kernel, and the interpreter's results.

FORMAT_OF = {'double': 'binary64', 'float': 'binary32'}


class _Stream:
    """Deterministic pseudo-random integers from a name, the same on every machine and Python."""

    def __init__(self, name):
        self.name, self.n = name, 0

    def bits(self, n):
        self.n += 1
        h = hashlib.blake2b(f'{self.name}:{self.n}'.encode(), digest_size=16).digest()
        return int.from_bytes(h, 'little') & ((1 << n) - 1)

    def pick(self, lo, hi):
        return lo + self.bits(16) % (hi - lo + 1)


def _num(f, rng, lo, hi, neg):
    m = rng.bits(f.p - 1) | (1 << (f.p - 1))
    return interp.canon(neg, m, rng.pick(lo, hi) - f.p + 1)


INF, NINF, NAN = (interp.INF, False), (interp.INF, True), interp.NaN
ZERO, NZERO = (interp.NUM, False, 0, 0), (interp.NUM, True, 0, 0)


def _largest(f):
    return interp.largest(f, False)   # Omega


def _state(lo, hi):
    """The stored pair (u, n) of [lo, hi]: (hi, -lo)."""
    return (hi, interp.neg(lo))


def _bounded(f, rng, sign=None):
    """A bounded interval [lo, hi] with full significands, of mixed signs unless `sign`."""
    while True:
        a = _num(f, rng, -4, 6, rng.bits(1) == 1 if sign is None else sign)
        b = _num(f, rng, -4, 6, rng.bits(1) == 1 if sign is None else sign)
        if interp.lt(a, b):
            return (a, b)
        if interp.lt(b, a):
            return (b, a)


def _cases(k, f):
    """The operands of the self-check's cases of k in format f, in the kernel's input order."""
    rng = _Stream(f'{k.name}:{f.name}')
    omega = _largest(f)
    empty = (NAN, NAN)
    whole = (INF, INF)
    pairs = list(k.pair_inputs)
    numbers = [v for g in _groups(k, 'input') if g.name not in k.pair_inputs for v in g.limbs]
    defaults = [r for r in k.requires if r[0] == 'interval']

    def st(iv):
        return _state(*iv)
    b1, b2, b3 = _bounded(f, rng), _bounded(f, rng), _bounded(f, rng, sign=False)
    point0 = (ZERO, ZERO)
    half = (_num(f, rng, -2, 3, True), INF)
    big = (interp.neg(omega), omega)
    t1 = _num(f, rng, -3, 3, rng.bits(1) == 1)
    cases = []
    if k.name == 'upward_make_1':
        a, b = b1
        return [[a, b], [b, a], [NAN, b], [INF, INF], [NINF, b], [a, a], [NINF, INF]]
    if defaults:
        (lo, hi) = b1
        return [[lo, hi], [INF, NINF], [NINF, INF], [half[0], INF]]
    if len(pairs) == 2:
        cases = [[st(b1), st(b2)], [st(b2), st(b3)], [empty, st(b1)], [whole, st(b2)], [st(half), st(b3)],
                 [st(point0), whole], [st(big), st(big)], [st(b1), st(b1)]]
        return [list(x) + list(y) for x, y in cases]
    if numbers:
        inside = b1[0]
        out = [[st(b1), t1], [st(b2), INF], [st(b3), NAN], [st(point0), NINF], [empty, t1], [whole, ZERO],
               [st(big), omega], [st(b1), inside]]
        return [list(x) + [t] for x, t in out]
    return [list(st(iv)) for iv in (b1, b2, half, point0, big)] + [list(empty), list(whole)]


def selftest_cases(k, kernels, ctype):
    """[(inputs, outputs)] of k for a limb type, the outputs the interpreter's (max_nl in MAXPD's
    form; the forms differ in the sign of a zero only, which the check does not compare)."""
    f = interp.parse_format(FORMAT_OF[ctype])
    m = interp.Machine(kernels, max_form='sel')
    return [(ins, m.run(k.name, f, ins)) for ins in _cases(k, f)]


def _value(v, ctype):
    if isinstance(v, bool):
        return 'true' if v else 'false'
    if v[0] == interp.INF:
        return f'{"-" if v[1] else ""}std::numeric_limits<{ctype}>::infinity()'
    if v[0] == interp.NAN:
        return f'std::numeric_limits<{ctype}>::quiet_NaN()'
    text = interp.format_limb(v)
    return (text + cpp.TYPES[ctype][1]) if text not in ('0x0p+0', '-0x0p+0') else text.replace('0x0p+0', '0.0') + \
        cpp.TYPES[ctype][1]


def selftest_function(k, kernels, ctype, literal):
    """The cases of k for ctype as one function: the operands read through volatile objects, or
    (literal) written as literals; the label of the first case whose result differs, or nullptr."""
    suffix = '_literal' if literal else ''
    lines = [f'inline const char* {k.name}_{ctype}{suffix}() noexcept {{']
    for i, (ins, outs) in enumerate(selftest_cases(k, kernels, ctype), 1):
        lines.append('    {')
        vals = {}
        for j, (v, kind) in enumerate(zip(ins, k.input_kinds)):
            t = 'bool' if kind == ir.MASK else ctype
            if literal:
                vals[k.input_limbs[j]] = _value(v, ctype)
            else:
                lines.append(f'        volatile {t} i{j} = {_value(v, ctype)};')
                vals[k.input_limbs[j]] = f'i{j}'
        args = []
        for g in _groups(k, 'input'):
            if g.name in k.pair_inputs:
                u, n = g.limbs
                args.append(f'pair_make({vals[u]}, {vals[n]})')
            else:
                args += [vals[v] for v in g.limbs]
        checks = []
        out_vals = dict(zip(k.output_limbs, outs))
        for g in _groups(k, 'output'):
            if g.name in k.pair_outputs:
                lines.append(f'        pair<{ctype}> o_{g.name};')
                args.append(f'o_{g.name}')
                u, n = g.limbs
                checks += [f'!same(pair_upper(o_{g.name}), {_value(out_vals[u], ctype)})',
                           f'!same(pair_nlower(o_{g.name}), {_value(out_vals[n], ctype)})']
            else:
                for v in g.limbs:
                    t = 'bool' if g.kind == ir.MASK else ctype
                    lines.append(f'        {t} o_{v};')
                    args.append(f'o_{v}')
                    checks.append(f'!same(o_{v}, {_value(out_vals[v], ctype)})')
        lines.append(f'        {k.name}({", ".join(args)});')
        label = f'{k.name} ({ctype}{", literal operands" if literal else ""}) case {i}'
        lines.append(f'        if ({" || ".join(checks)}) return "{label}";')
        lines.append('    }')
    return lines + ['    return nullptr;', '}']


