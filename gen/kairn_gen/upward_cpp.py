# The spellings of the scalar statements (the two-number form, and the scalar statements of the
# register form): one operation per expression, as the scalar printer of cpp.py writes them.

def scalar_spell(ctype):
    """{op: format} of a scalar statement for a limb type: double, float, or a cpp.Limb (the
    emulated type, whose add_ru, mul_ru and max_nl are its own functions)."""
    spell = {
        'add_ru': '{0} + {1}', 'mul_ru': '{0} * {1}', 'max_nl': '{0} > {1} ? {0} : {1}',
        'neg': '-{0}', 'abs': 'abs_bits({0})', 'copy': '{0}',
        'lt': '{1} > {0}', 'le': '{1} >= {0}', 'eq': '{0} == {1}',
        'and': '{0} & {1}', 'or': '{0} | {1}', 'not': '!{0}', 'select': '{0} ? {1} : {2}',
    }
    if isinstance(ctype, cpp.Limb):
        spell.update(add_ru='add_ru({0}, {1})', mul_ru='mul_ru({0}, {1})', max_nl='max_nl({0}, {1})')
    return spell


def _unord(args):
    a, b = args
    return f'{a} != {a}' if a == b else f'({a} != {a}) | ({b} != {b})'


def _scalar_literal(name, ctype):
    if isinstance(ctype, cpp.Limb):
        if name == ir.ZERO:
            return f'{ctype.name}()'
        return cpp.literal(name, None, ctype)
    return cpp.literal(name, None, ctype)


def scalar_expr(op, args, ctype):
    if op == 'unord':
        return f'unord({args[0]}, {args[1]})' if isinstance(ctype, cpp.Limb) else _unord(args)
    return scalar_spell(ctype)[op].format(*args)


