def _kernels(kernels):
    return getattr(kernels, 'upward', kernels)


def _rounds(k):
    return any(st.op in ir.ROUNDED_UP for st in k.body)


def _groups(k, side):
    """The inputs (side 'input') or outputs of k as groups, the two one-limb groups of the lanes of a
    pair as one group named by the pair, its limbs the lanes in order."""
    pairs = k.pair_inputs if side == 'input' else k.pair_outputs
    by_lane = {lanes[0]: (name, lanes) for name, lanes in pairs.items()}
    rest = {lanes[1] for lanes in pairs.values()}
    out = []
    for g in (k.inputs if side == 'input' else k.outputs):
        if g.name in by_lane:
            name, lanes = by_lane[g.name]
            out.append(ir.Group(name, tuple(lanes)))
        elif g.name not in rest:
            out.append(g)
    return out


