# The register form: x86-64 and arm64, double and float.

class Reg:
    """The spellings of the one-register form of one backend and limb type."""

    def __init__(self, backend, ctype):
        self.backend, self.ctype = backend, ctype
        x86, d = backend == 'SSE2', ctype == 'double'
        self.x86, self.double = x86, d
        if x86:
            self.vec = '__m128d' if d else '__m128'
            self.mask = self.vec
            s = 'pd' if d else 'ps'
            self.s = s
        else:
            self.vec = 'float64x2_t' if d else 'float32x2_t'
            self.mask = 'uint64x2_t' if d else 'uint32x2_t'
        self.lit = lambda name: cpp.literal(name, None, ctype)

    # The two-lane constants, the upper lanes of an __m128 +0.
    def set2(self, l0, l1):
        if self.x86:
            if self.double:
                if l0 == l1:
                    return '_mm_setzero_pd()' if l0 == '0.0' else f'_mm_set1_pd({l0})'
                return f'_mm_set_pd({l1}, {l0})'
            return '_mm_setzero_ps()' if l0 == l1 == '0.0f' else f'_mm_set_ps(0.0f, 0.0f, {l1}, {l0})'
        if self.double:
            if l0 == l1:
                return f'vdupq_n_f64({l0})'
            return f'vcombine_f64(vdup_n_f64({l0}), vdup_n_f64({l1}))'
        if l0 == l1:
            return f'vdup_n_f32({l0})'
        return f'vset_lane_f32({l1}, vdup_n_f32({l0}), 1)'

    def swap(self, r, mask):
        if self.x86:
            return (f'_mm_shuffle_pd({r}, {r}, 1)' if self.double
                    else f'_mm_shuffle_ps({r}, {r}, _MM_SHUFFLE(3, 2, 0, 1))')
        if self.double:
            return f'vextq_{"u" if mask else "f"}64({r}, {r}, 1)'
        return f'vrev64_{"u" if mask else "f"}32({r})'

    def bcast(self, r, lane, mask):
        if self.x86:
            if self.double:
                return f'_mm_unpack{"lo" if lane == 0 else "hi"}_pd({r}, {r})'
            return f'_mm_shuffle_ps({r}, {r}, _MM_SHUFFLE(3, 2, {lane}, {lane}))'
        if self.double:
            return f'vdupq_laneq_{"u" if mask else "f"}64({r}, {lane})'
        return f'vdup_lane_{"u" if mask else "f"}32({r}, {lane})'

    def splat(self, s, mask):
        if mask:
            if self.x86:
                if self.double:
                    return f'_mm_castsi128_pd(_mm_set1_epi64x(-static_cast<long long>({s})))'
                return f'_mm_castsi128_ps(_mm_set_epi32(0, 0, -static_cast<int>({s}), -static_cast<int>({s})))'
            if self.double:
                return f'vdupq_n_u64(std::uint64_t{{0}} - static_cast<std::uint64_t>({s}))'
            return f'vdup_n_u32(std::uint32_t{{0}} - static_cast<std::uint32_t>({s}))'
        return self.set2(s, s) if not (self.x86 and self.double) else f'_mm_set1_pd({s})'

    def make(self, s0, s1):
        if self.x86:
            return f'_mm_set_pd({s1}, {s0})' if self.double else f'_mm_set_ps(0.0f, 0.0f, {s1}, {s0})'
        if self.double:
            return f'vcombine_f64(vdup_n_f64({s0}), vdup_n_f64({s1}))'
        return f'vset_lane_f32({s1}, vdup_n_f32({s0}), 1)'

    def lane_value(self, r, lane):
        if self.x86:
            if self.double:
                return f'_mm_cvtsd_f64({r})' if lane == 0 else f'_mm_cvtsd_f64(_mm_unpackhi_pd({r}, {r}))'
            return f'_mm_cvtss_f32({r})' if lane == 0 else f'_mm_cvtss_f32(_mm_shuffle_ps({r}, {r}, _MM_SHUFFLE(1, 1, 1, 1)))'
        return f'vgetq_lane_f64({r}, {lane})' if self.double else f'vget_lane_f32({r}, {lane})'

    def lane_mask(self, r, lane):
        if self.x86:
            return f'(_mm_movemask_{self.s}({r}) & {1 << lane}) != 0'
        return f'vgetq_lane_u64({r}, {lane}) != 0' if self.double else f'vget_lane_u32({r}, {lane}) != 0'

    def sign(self, lanes):
        """The constant whose bits are the sign bits of the lanes in `lanes` (0, 1)."""
        z = '0.0' if self.double else '0.0f'
        m = '-0.0' if self.double else '-0.0f'
        return (m if 0 in lanes else z), (m if 1 in lanes else z)

    def op(self, op, args):
        """A pair line's operation on registers, operands materialized."""
        two = ', '.join(args)
        if self.x86:
            s = self.s
            neg = self.set2(*self.sign((0, 1)))
            table = {
                'add_ru': f'_mm_add_{s}({two})', 'mul_ru': f'_mm_mul_{s}({two})', 'max_nl': f'_mm_max_{s}({two})',
                'unord': f'_mm_cmpunord_{s}({two})', 'lt': f'_mm_cmplt_{s}({two})', 'le': f'_mm_cmple_{s}({two})',
                'eq': f'_mm_cmpeq_{s}({two})', 'and': f'_mm_and_{s}({two})', 'or': f'_mm_or_{s}({two})',
                'not': f'detail::not_mask({two})', 'neg': f'_mm_xor_{s}({two}, {neg})',
                'abs': f'_mm_andnot_{s}({neg}, {two})',
            }
            return table[op]
        f = 'q_f64' if self.double else '_f32'
        u = 'q_u64' if self.double else '_u32'
        if op == 'unord':
            return f'detail::is_nan({args[0]})' if args[0] == args[1] else f'detail::unord({two})'
        table = {
            'add_ru': f'vadd{f}({two})', 'mul_ru': f'vmul{f}({two})', 'max_nl': f'vmaxnm{f}({two})',
            'lt': f'vclt{f}({two})', 'le': f'vcle{f}({two})', 'eq': f'vceq{f}({two})',
            'and': f'vand{u}({two})', 'or': f'vorr{u}({two})', 'not': f'detail::not_mask({two})',
            'neg': f'vneg{f}({two})', 'abs': f'vabs{f}({two})',
        }
        return table[op]

    def flip(self, r, lane):
        """The sign of one lane changed (a pair line neg | copy or copy | neg)."""
        if self.x86:
            return f'_mm_xor_{self.s}({r}, {self.set2(*self.sign((lane,)))})'
        return f'detail::flip{lane}({r})'

    def bits_op(self, op, value, mask):
        """value AND mask, value AND NOT mask, value OR mask, on the bits of a register."""
        if self.x86:
            return {'and': f'_mm_and_{self.s}({mask}, {value})', 'andnot': f'_mm_andnot_{self.s}({mask}, {value})',
                    'or': f'_mm_or_{self.s}({value}, {mask})'}[op]
        if self.double:
            fn = {'and': 'vandq_u64', 'andnot': 'vbicq_u64', 'or': 'vorrq_u64'}[op]
            return f'vreinterpretq_f64_u64({fn}(vreinterpretq_u64_f64({value}), {mask}))'
        fn = {'and': 'vand_u32', 'andnot': 'vbic_u32', 'or': 'vorr_u32'}[op]
        return f'vreinterpret_f32_u32({fn}(vreinterpret_u32_f32({value}), {mask}))'

    def blend(self, m, a, b):
        if self.x86:
            return f'detail::blend({m}, {a}, {b})'
        return f'vbsl{"q_f64" if self.double else "_f32"}({m}, {a}, {b})'

    def mul_lane(self, a, r, lane):
        return f'vmul{"q_laneq_f64" if self.double else "_lane_f32"}({a}, {r}, {lane})'


class _Function:
    """The lines of one function being printed, and the registers derived on the way."""

    def __init__(self, pad='    '):
        self.lines, self.pad, self.names, self.derived = [], pad, set(), {}

    def name(self, n):
        if n in self.names:
            raise PrintError(f'C++ name clash: {n}')
        self.names.add(n)
        return n

    def add(self, text):
        self.lines.append(self.pad + text)


def _sv(a, L, ctype):
    """A scalar operand of the register or the two-number form: a name or a literal."""
    return _scalar_literal(a.name, ctype) if a.const else a.name


def register_function(k, R, kernels):
    """One kernel in the one-register form of backend R (a Reg)."""
    L = Listing(k)
    ctype = R.ctype
    fn = _Function()
    ins = []
    for g in _groups(k, 'input'):
        if g.name in k.pair_inputs:
            ins.append(f'{R.vec} {fn.name(g.name)}')
        else:
            for v in g.limbs:
                ins.append(f'{"bool" if g.kind == ir.MASK else ctype} {fn.name(v)}')
    outs = []
    for g in _groups(k, 'output'):
        if g.name in k.pair_outputs:
            outs.append(f'{R.vec}& {fn.name(g.name + "_out")}')
        else:
            for v in g.limbs:
                outs.append(f'{"bool" if g.kind == ir.MASK else ctype}& {fn.name(v + "_out")}')
    # Clean upper lanes of a mask register (float on x86-64): every bit of lanes 2 and 3 clear, so
    # that the register can be ORed into a value as its NaN arm.
    clean = set()

    def extract(key):
        """The lanes of the register of `key` that scalar statements read, as numbers (masks)."""
        for i, v in enumerate(L.pairs[key]):
            if v in L.read:
                r = L.reg[key]
                if L.kind[v] == ir.MASK:
                    fn.add(f'const bool {fn.name(v)} = {R.lane_mask(r, i)};')
                else:
                    fn.add(f'const {ctype} {fn.name(v)} = {R.lane_value(r, i)};')

    # The inputs: the pin on the first pair input of a kernel that rounds, a barrier on every other
    # number and register; then the lanes the scalar statements read.
    for g in _groups(k, 'input'):
        if g.kind == ir.MASK:
            continue
        names = [g.name] if g.name in k.pair_inputs else list(g.limbs)
        for v in names:
            pin = L.rounds and g.name == L.first
            fn.add(f'KAIRN_DETAIL_UPWARD_{"PIN" if pin else "BARRIER"}({v});')
    for name in k.pair_inputs:
        extract(('input', name))

    def materialize(form, mask):
        """The expression of an operand form, deriving a register where one is needed."""
        kind = form[0]
        if kind == 'reg':
            return L.reg[form[1]]
        key = ('derived',) + tuple(str(x) for x in form)
        if key in fn.derived:
            return fn.derived[key]
        if kind == 'swap':
            r = L.reg[form[1]]
            name, text = f'{r}_swap', R.swap(r, mask)
            if mask and form[1] in clean:
                clean.add(key)
        elif kind == 'bcast':
            r = L.reg[form[1]]
            name, text = f'{r}_lane{form[2]}', R.bcast(r, form[2], mask)
            if mask and form[1] in clean:
                clean.add(key)
        elif kind == 'const':
            c0, c1 = form[1], form[2]
            if mask:
                raise PrintError(f'kernel {k.name}: a mask of two constants')
            label = {'0': 'zero', 'inf': 'inf', 'nan': 'nan'}
            name = f'{label.get(c0, c0)}_{label.get(c1, c1)}_k'
            text = R.set2(R.lit(c0), R.lit(c1))
        elif kind == 'splat':
            s = form[1]
            name, text = f'{s.name}_splat', R.splat(s.name, mask)
            if mask:
                clean.add(key)
        else:
            a, b = form[1], form[2]
            if mask:
                raise PrintError(f'kernel {k.name}: a mask made of two scalar masks (rule P5)')
            name = f'{a.name if not a.const else "k" + a.name}_{b.name if not b.const else "k" + b.name}_make'
            text = R.make(_sv(a, L, ctype), _sv(b, L, ctype))
        fn.add(f'const {R.mask if mask else R.vec} {fn.name(name)} = {text};')
        fn.derived[key] = name
        return name

    def is_clean(form, expr):
        if R.double or not R.x86:
            return True
        if form[0] == 'reg':
            return form[1] in clean
        return ('derived',) + tuple(str(x) for x in form) in clean

    for st in k.body:
        if st.lane == 1:
            continue
        if st.lane is None:
            d = st.dsts[0]
            args = [_sv(a, L, ctype) for a in st.args]
            text = scalar_expr(st.op, args, ctype)
            vtype = 'bool' if L.kind[d] == ir.MASK else ctype
            if d in L.signed:
                fn.add(f'{vtype} {fn.name(d)} = {text};')
                fn.add(f'KAIRN_DETAIL_UPWARD_BARRIER({d});')
            elif d in L.scalar_outputs and vtype != 'bool':
                fn.add(f'{vtype} {fn.name(d)} = {text};')
            else:
                fn.add(f'const {vtype} {fn.name(d)} = {text};')
            continue
        s0, s1 = L.line_of[st.line]
        key = ('line', st.line)
        r = fn.name(L.reg[key])
        mask = ir.OPS[s0.op][1] == ir.MASK
        forms = [L.operand(a, b) for a, b in zip(s0.args, s1.args)]
        in_kinds = ir.OPS[s0.op][0] if s0.op == s1.op else (ir.LIMB,)
        if s0.op != s1.op:
            # neg | copy, copy | neg: the sign of one lane changed.
            text = R.flip(materialize(forms[0], False), 0 if s0.op == 'neg' else 1)
        elif s0.op == 'copy':
            text = materialize(forms[0], False)
        elif s0.op == 'select':
            m = materialize(forms[0], True)
            arm_a, arm_b = forms[1], forms[2]
            if arm_a[0] == 'const' and arm_a[1:] == (ir.ZERO, ir.ZERO):
                text = R.bits_op('andnot', materialize(arm_b, False), m)
            elif arm_b[0] == 'const' and arm_b[1:] == (ir.ZERO, ir.ZERO):
                text = R.bits_op('and', materialize(arm_a, False), m)
            elif arm_a[0] == 'const' and arm_a[1:] == ('nan', 'nan') and is_clean(forms[0], m):
                text = R.bits_op('or', materialize(arm_b, False), m)
            else:
                text = R.blend(m, materialize(arm_a, False), materialize(arm_b, False))
        elif s0.op == 'mul_ru' and not R.x86 and any(f[0] == 'bcast' for f in forms):
            # arm64: a product by a lane, the broadcast taken as it is (FMUL by element).
            i = 1 if forms[1][0] == 'bcast' else 0
            other = materialize(forms[1 - i], False)
            text = R.mul_lane(other, L.reg[forms[i][1]], forms[i][2])
        else:
            args = [materialize(f, kind == ir.MASK) for f, kind in zip(forms, in_kinds)]
            text = R.op(s0.op, args)
            if mask and s0.op in ('unord', 'lt'):
                clean.add(key)
            elif mask and s0.op == 'and' and any(is_clean(f, x) for f, x in zip(forms, args)):
                clean.add(key)
            elif mask and s0.op == 'or' and all(is_clean(f, x) for f, x in zip(forms, args)):
                clean.add(key)
        vtype = R.mask if mask else R.vec
        barrier = st.line in L.signed_lines or r in k.pair_outputs
        if barrier:
            fn.add(f'{vtype} {r} = {text};')
            if st.line in L.signed_lines:
                fn.add(f'KAIRN_DETAIL_UPWARD_BARRIER({r});')
        else:
            fn.add(f'const {vtype} {r} = {text};')
        extract(key)
    # The outputs: a barrier on every register and number, then the stores.
    for g in _groups(k, 'output'):
        if g.name in k.pair_outputs:
            fn.add(f'KAIRN_DETAIL_UPWARD_BARRIER({g.name});')
            fn.add(f'{g.name}_out = {g.name};')
        else:
            for v in g.limbs:
                if g.kind != ir.MASK:
                    fn.add(f'KAIRN_DETAIL_UPWARD_BARRIER({v});')
                fn.add(f'{v}_out = {v};')
    return [f'KAIRN_GEN_FORCEINLINE void {k.name}({", ".join(ins + outs)}) noexcept {{'] + fn.lines + ['}']


