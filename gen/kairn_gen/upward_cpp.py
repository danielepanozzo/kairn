# The array forms: the scalar listing with every value a register of W lanes.

class Packed:
    """The spellings of an array form: AVX2 or NEON, double or float."""

    def __init__(self, backend, ctype):
        self.backend, self.ctype = backend, ctype
        d = ctype == 'double'
        self.lit = lambda name: cpp.literal(name, None, ctype)
        if backend == 'AVX2':
            self.vec = '__m256d' if d else '__m256'
            self.mask = self.vec
            self.w = 4 if d else 8
            s = 'pd' if d else 'ps'
            m = '-0.0' if d else '-0.0f'
            self.spell = {
                'add_ru': f'_mm256_add_{s}({{0}}, {{1}})', 'mul_ru': f'_mm256_mul_{s}({{0}}, {{1}})',
                'max_nl': f'_mm256_max_{s}({{0}}, {{1}})',
                'unord': f'_mm256_cmp_{s}({{0}}, {{1}}, _CMP_UNORD_Q)',
                'neg': f'_mm256_xor_{s}({{0}}, _mm256_set1_{s}({m}))',
                'abs': f'_mm256_andnot_{s}(_mm256_set1_{s}({m}), {{0}})',
                'lt': f'_mm256_cmp_{s}({{0}}, {{1}}, _CMP_LT_OQ)', 'le': f'_mm256_cmp_{s}({{0}}, {{1}}, _CMP_LE_OQ)',
                'eq': f'_mm256_cmp_{s}({{0}}, {{1}}, _CMP_EQ_OQ)',
                'and': f'_mm256_and_{s}({{0}}, {{1}})', 'or': f'_mm256_or_{s}({{0}}, {{1}})',
                'not': 'detail::not_mask({0})', 'select': f'_mm256_blendv_{s}({{2}}, {{1}}, {{0}})', 'copy': '{0}',
            }
            self.set1 = f'_mm256_set1_{s}({{0}})'
            self.zero = f'_mm256_setzero_{s}()'
            self.load = f'_mm256_loadu_{s}({{0}})'
            self.store = f'_mm256_storeu_{s}({{0}}, {{1}})'
        else:
            self.vec = 'float64x2_t' if d else 'float32x4_t'
            self.mask = 'uint64x2_t' if d else 'uint32x4_t'
            self.w = 2 if d else 4
            s, u = ('f64', 'u64') if d else ('f32', 'u32')
            self.spell = {
                'add_ru': f'vaddq_{s}({{0}}, {{1}})', 'mul_ru': f'vmulq_{s}({{0}}, {{1}})',
                'max_nl': f'vmaxnmq_{s}({{0}}, {{1}})', 'unord': 'detail::unord({0}, {1})',
                'neg': f'vnegq_{s}({{0}})', 'abs': f'vabsq_{s}({{0}})',
                'lt': f'vcltq_{s}({{0}}, {{1}})', 'le': f'vcleq_{s}({{0}}, {{1}})', 'eq': f'vceqq_{s}({{0}}, {{1}})',
                'and': f'vandq_{u}({{0}}, {{1}})', 'or': f'vorrq_{u}({{0}}, {{1}})',
                'not': 'detail::not_mask({0})', 'select': f'vbslq_{s}({{0}}, {{1}}, {{2}})', 'copy': '{0}',
            }
            self.set1 = f'vdupq_n_{s}({{0}})'
            self.zero = f'vdupq_n_{s}({self.lit(ir.ZERO)})'
            self.load = f'vld1q_{s}({{0}})'
            self.store = f'vst1q_{s}({{0}}, {{1}})'

    def operand(self, a):
        if not a.const:
            return a.name
        if a.name == ir.ZERO:
            return self.zero
        return self.set1.format(self.lit(a.name))

    def expr(self, op, args):
        if op == 'unord' and self.backend == 'NEON' and args[0] == args[1]:
            return f'detail::is_nan({args[0]})'
        return self.spell[op].format(*args)


def _array_parameters(k, ctype):
    ins = []
    for g in _groups(k, 'input'):
        if g.name in k.pair_inputs:
            ins += [f'const {ctype}* {v}_in' for v in g.limbs]
        else:
            ins += [f'{ctype} {v}' for v in g.limbs]
    outs = [f'{ctype}* {v}_out' for v in k.output_limbs]
    return ins + outs + ['std::size_t n']


def _invariant(k):
    """The statements that depend on the number inputs and the constants only: computed once,
    before the loop."""
    numbers = {v for g in _groups(k, 'input') if g.name not in k.pair_inputs for v in g.limbs}
    out = set()
    for st in k.body:
        if all(a.const or a.name in numbers or a.name in out for a in st.args):
            out.add(st.dsts[0])
    return out


def _tail_call(k, start, pad):
    """The loop of the one-register form over the elements from `start` on."""
    args = []
    for g in _groups(k, 'input'):
        if g.name in k.pair_inputs:
            u, n = g.limbs
            args.append(f'pair_make({u}_in[i_], {n}_in[i_])')
        else:
            args += list(g.limbs)
    (zname, (zu, zn)), = k.pair_outputs.items()
    return [f'{pad}for (; i_ < n; ++i_) {{',
            f'{pad}    pair<{{T}}> {zname}_;',
            f'{pad}    {k.name}({", ".join(args)}, {zname}_);',
            f'{pad}    {zu}_out[i_] = pair_upper({zname}_);',
            f'{pad}    {zn}_out[i_] = pair_nlower({zname}_);',
            f'{pad}}}']


def array_function(k, ctype, P):
    """The array form of k for limb type ctype: with P (a Packed) the first W (n / W) elements in
    registers of W lanes and the rest by the one-register form; with P None, every element by the
    one-register form."""
    L = Listing(k)
    lines = [f'inline void {k.name}_arrays({", ".join(_array_parameters(k, ctype))}) noexcept {{',
             '    std::size_t i_ = 0;']
    if P is not None:
        inv = _invariant(k)
        pad = '        '
        body, before = [], []
        names = set()
        # The number inputs: a barrier, then broadcast once.
        for g in _groups(k, 'input'):
            if g.name not in k.pair_inputs:
                for v in g.limbs:
                    before += [f'    KAIRN_DETAIL_UPWARD_BARRIER({v});',
                               f'    {P.vec} {v}_v = {P.set1.format(v)};',
                               f'    KAIRN_DETAIL_UPWARD_BARRIER({v}_v);']
        rename = {v: f'{v}_v' for g in _groups(k, 'input') if g.name not in k.pair_inputs for v in g.limbs}
        for g in _groups(k, 'input'):
            if g.name in k.pair_inputs:
                pin = L.rounds and g.name == L.first
                for v in g.limbs:
                    body += [f'{pad}{P.vec} {v} = {P.load.format(f"{v}_in + i_")};',
                             f'{pad}KAIRN_DETAIL_UPWARD_{"PIN" if pin else "BARRIER"}({v});']
                    names.add(v)
        outputs = set(k.output_limbs)
        for st in k.body:
            d = st.dsts[0]
            args = [P.operand(a) if a.const else rename.get(a.name, a.name) for a in st.args]
            vtype = P.mask if L.kind[d] == ir.MASK else P.vec
            text = P.expr(st.op, args)
            target = before if d in inv else body
            p = '    ' if d in inv else pad
            if d in inv:
                rename[d] = d
            if d in L.signed or d in outputs:
                target.append(f'{p}{vtype} {d} = {text};')
                if d in L.signed:
                    target.append(f'{p}KAIRN_DETAIL_UPWARD_BARRIER({d});')
            else:
                target.append(f'{p}const {vtype} {d} = {text};')
        for v in k.output_limbs:
            body += [f'{pad}KAIRN_DETAIL_UPWARD_BARRIER({v});', f'{pad}{P.store.format(f"{v}_out + i_", v)};']
        lines += before + [f'    for (; i_ + {P.w} <= n; i_ += {P.w}) {{'] + body + ['    }']
    lines += [x.replace('{T}', ctype) for x in _tail_call(k, '0', '    ')]
    return lines + ['}']


