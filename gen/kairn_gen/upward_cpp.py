"""The C++ printers of the round-up interval: include/kairn/gen/upward.hpp and
tests/emulated/gen/upward.hpp (docs/developer/design/upward.md, "The pair form", "The printers",
"Barriers").

The listings of the upward family (ir.KernelSet.upward) are scalar; a pair line names the two
statements that are the two lanes of one instruction (Kernel.pair_lines, checked by rules P1 to P5).
From each listing this module prints:

- the one-register form: every pair line one operation on a register of two lanes, lane 0 the
  statement on the left; x86-64 (__m128d, and __m128 with its two upper lanes +0 in every value),
  arm64 (float64x2_t, float32x2_t). An operand of a pair line is the register of a pair in its
  order, the same swapped, a broadcast of one of its lanes (on arm64 a product by a lane takes it
  as it is), a broadcast of a scalar, two scalars made into a register, or a register of two
  constants (rule P2). A scalar statement reads lanes of registers as numbers (lane 0 costs nothing,
  lane 1 a move) and computes as the two-number form does;
- the two-number form: each pair line its two statements, each a C++ expression of one operation,
  max_nl as `a > b ? a : b` (MAXPD's form), on every target, and wherever KAIRN_UPWARD_FORM is
  KAIRN_UPWARD_FORM_NUMBERS;
- the array forms of the kernels the functions on arrays run (ARRAYS): the scalar listing, the
  pairing ignored, each value a register of W lanes (AVX2 where the file has -mavx2, NEON on
  arm64), the first W (n / W) elements so, the rest element by element by the one-register form;
  elsewhere a loop of the one-register form over every element;
- the tables of kairn::upward::self_test() (the design page, "The self-check", items 3 and 4):
  fixed operands of every kernel, read through volatile objects and written as literals, against
  the outputs the interpreter computes; and the status of each kernel, for kairn::unverified.

The barriers (the design page, "Barriers"): KAIRN_DETAIL_UPWARD_PIN on the first pair input of a
kernel that rounds (an add_ru or a mul_ru: on MSVC the barrier per scope reaches its operations
through that input, rule U6), KAIRN_DETAIL_UPWARD_BARRIER on every other input and on every
output that is a number or a register of numbers, and on the result of every sign change (neg,
abs, or a pair line of them) that is an operand of add_ru or mul_ru. A mask, the result of
comparisons, is exact in every mode and gets none. The macros are those of include/kairn/upward.hpp,
which must be included first.

Linkage (the design page, "Linkage"): the kernels that round, the array forms and the self-check
functions have internal linkage (an unnamed namespace), so that every file runs its own copy,
compiled with its options; the exact kernels, whose results are the same under every option and
mode, are ordinary inline functions, which the members of kairn::upward::Interval<T> (a class of
external linkage) may call. Like the other C++ printers, this one is trusted: it is tested bit for
bit against the interpreter in every form (gen/tests/test_upward_cxx.py).
"""
