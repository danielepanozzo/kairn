# The shape of a listing: its pairs, the register of each, and what the printers read of them.

class Listing:
    """What the printers need to know of one kernel of the family."""

    def __init__(self, k):
        self.k = k
        for st in k.body:
            if st.is_call:
                raise PrintError(f'kernel {k.name}: the printers of the round-up interval print no call '
                                 f'(line {st.line}): write the callee\'s statements')
        self.kind = dict(zip(k.input_limbs, k.input_kinds))
        for st in k.body:
            self.kind[st.dsts[0]] = ir.OPS[st.op][1]
        # The pairs: {key: (lane 0, lane 1)}, a key ('input', NAME) or ('line', LINE); the register
        # of each; the pair and the lane of every lane value.
        self.pairs, self.reg, self.lane = {}, {}, {}
        outputs = {lanes: name for name, lanes in k.pair_outputs.items()}
        for name, lanes in k.pair_inputs.items():
            self.pairs[('input', name)] = tuple(lanes)
            self.reg[('input', name)] = name
        self.line_of = {}
        for s0, s1 in k.pair_lines():
            key = ('line', s0.line)
            lanes = (s0.dsts[0], s1.dsts[0])
            self.pairs[key] = lanes
            self.reg[key] = outputs.get(lanes, f'{lanes[0]}_{lanes[1]}')
            self.line_of[s0.line] = (s0, s1)
        for key, lanes in self.pairs.items():
            for i, v in enumerate(lanes):
                self.lane[v] = (key, i)
        self.first = next(iter(k.pair_inputs), None)
        self.rounds = _rounds(k)
        paired = {v for lanes in k.pair_outputs.values() for v in lanes}
        self.scalar_outputs = [v for v in k.output_limbs if v not in paired]
        # The lanes that scalar statements read, and the values that are sign changes used as an
        # operand of add_ru or mul_ru.
        self.read = set()
        rounded_operands = set()
        for st in k.body:
            names = [a.name for a in st.args if not a.const]
            if st.lane is None:
                self.read |= {n for n in names if n in self.lane}
            if st.op in ir.ROUNDED_UP:
                rounded_operands |= set(names)
        self.signed = set()
        for st in k.body:
            if st.op in SIGN_CHANGES and st.dsts[0] in rounded_operands:
                self.signed.add(st.dsts[0])
        # A pair line is a sign change when either lane is (neg | copy included).
        self.signed_lines = set()
        for line, (s0, s1) in self.line_of.items():
            if {s0.op, s1.op} & SIGN_CHANGES and {s0.dsts[0], s1.dsts[0]} & rounded_operands:
                self.signed_lines.add(line)

    def lanes_of(self, key):
        return self.pairs[key]

    def operand(self, a, b):
        """The form of the operand position (a | b) of a pair line (rule P2): ('reg', key),
        ('swap', key), ('bcast', key, lane), ('const', c0, c1), ('splat', s), ('make', a, b)."""
        if a.const and b.const:
            return ('const', a.name, b.name)
        if not a.const and not b.const and a.name in self.lane and b.name in self.lane:
            (ka, la), (kb, lb) = self.lane[a.name], self.lane[b.name]
            if ka != kb:
                raise PrintError(f'kernel {self.k.name}: ({a} | {b}) names two pairs (rule P2)')
            if (la, lb) == (0, 1):
                return ('reg', ka)
            if (la, lb) == (1, 0):
                return ('swap', ka)
            return ('bcast', ka, la)
        if (not a.const and a.name in self.lane) or (not b.const and b.name in self.lane):
            raise PrintError(f'kernel {self.k.name}: ({a} | {b}) puts a scalar beside a lane (rule P4)')
        if not a.const and not b.const and a.name == b.name:
            return ('splat', a)
        return ('make', a, b)


